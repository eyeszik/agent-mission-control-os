function decode(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(decode);
  if (node === null || typeof node !== 'object') return node;
  const entries = Object.entries(node as Rec);
  const [tag, raw] = entries[0] ?? [];
  if (entries.length === 1 && typeof raw === 'string') {
    if (tag === '$int') return Number.isSafeInteger(Number(raw)) ? Number(raw) : BigInt(raw);
    if (tag === '$float') return decodeFloat(raw);
    if (tag === '$utf16') return raw.split(' ').map((u) => String.fromCharCode(parseInt(u, 16))).join('');
  }
  return Object.fromEntries(entries.map(([k, v]) => [k, decode(v)]));
}

function decodeFloat(raw: string): number | CanonicalFloat {
  const named: Record<string, number> = { nan: Number.NaN, inf: Infinity, '-inf': -Infinity };
  const value = named[raw] ?? Number(raw);
  return Number.isInteger(value) || Object.is(value, -0) ? new CanonicalFloat(value) : value;
}

/** Numbers compare numerically: a JS number cannot say int or float (hashed paths keep CanonicalFloat). */
function plain(node: unknown): unknown {
  if (node instanceof CanonicalFloat) return node.value;
  if (Array.isArray(node)) return node.map(plain);
  if (node === null || typeof node !== 'object') return node;
  return Object.fromEntries(Object.entries(node as Rec).map(([k, v]) => [k, plain(v)]));
}

