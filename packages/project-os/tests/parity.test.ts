function dryRun(ops: unknown): unknown {
  const provider = new DryRunProvider(200);
  const pair = (r: { external_ref: string; observed: unknown }) => [r.external_ref, r.observed];
  return (ops as Rec[]).map((op) => {
    const prepared = op.prepared as Record<string, PyJson>;
    switch (op.op) {
      case 'prepare': return provider.prepare(op.request as never);
      case 'validate': return provider.validate(prepared);
      case 'preview': return provider.preview(prepared);
      case 'publish': return pair(provider.publish(prepared, op.key as string));
      case 'verify': { const r = provider.verify(op.key as string); return r ? pair(r) : null; }
      case 'update': return pair(provider.update(op.ref as string, prepared));
      default: return provider.remove(op.ref as string);
    }
  });
}

