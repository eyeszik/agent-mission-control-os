function run(testCase: FixtureCase): string | undefined {
  if (testCase.divergence) return undefined;
  let result: unknown;
  let thrown: Error | undefined;
  try {
    result = invoke(testCase);
  } catch (error) {
    thrown = error as Error;
  }
  if (testCase.error) {
    if (!thrown) return `expected ${testCase.error.type}, got a result`;
    if (testCase.error.type === 'ValidationError') return undefined;
    const same = thrown.name === testCase.error.type && thrown.message === testCase.error.message;
    return same ? undefined : `expected ${testCase.error.type}: ${testCase.error.message}; got ${thrown.name}: ${thrown.message}`;
  }
  if (thrown) return `unexpected ${thrown.name}: ${thrown.message}`;
  // Zod's optional fields omit what Pydantic dumps as null.
  return compare(result, testCase.ok, testCase.call === 'validate');
}

function compare(result: unknown, expectedRaw: unknown, dropNulls = false): string | undefined {
  const actual = JSON.stringify(plain(sortKeys(result === undefined ? null : result, dropNulls)), replacer);
  const expected = JSON.stringify(plain(sortKeys(decode(expectedRaw), dropNulls)), replacer);
  return actual === expected ? undefined : `expected ${expected.slice(0, 300)} got ${actual.slice(0, 300)}`;
}

function replacer(_key: string, value: unknown): unknown {
  if (typeof value === 'number' && !Number.isFinite(value)) return String(value);
  if (typeof value === 'bigint') return value.toString();
  return value;
}

function sortKeys(node: unknown, dropNulls = false): unknown {
  if (node instanceof CanonicalFloat) return node;
  if (Array.isArray(node)) return node.map((n) => sortKeys(n, dropNulls));
  if (node === null || typeof node !== 'object') return node;
  const entries = Object.entries(node as Rec).filter(([, v]) => v !== undefined && !(dropNulls && v === null));
  return Object.fromEntries(entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([k, v]) => [k, sortKeys(v, dropNulls)]));
}

