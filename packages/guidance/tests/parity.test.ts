function expectPackSummary(name: string, registry: GuidanceRegistry, expected: Fixture['packs'][number]['expect']): void {
  expect(expected, name).toBeDefined();
  expect(registry.registryHash, name).toBe(expected?.registry_hash);
  const summary = registry.packs.map((pack) => ({
    id: pack.id,
    content_hash: pack.content_hash,
    dump: stored(packDump(pack, true)),
    section_reprs: pack.sections.map((section) => pyReprSection(pack, section.id)),
  }));
  const wanted = expected?.packs ?? [];
  expect(summary.map((p) => [p.id, p.content_hash]), name).toEqual(wanted.map((p) => [p.id, p.content_hash]));
  summary.forEach((p, i) => {
    expect(p.dump.sha256, `${name}/${p.id}`).toBe(wanted[i]?.dump.sha256);
    expect(p.section_reprs, `${name}/${p.id}`).toEqual(wanted[i]?.section_reprs);
  });
}

function stored(value: unknown): Stored {
  const text = canonicalJson(value);
  return { sha256: sha256Text(text), length: text.length };
}

function pyReprSection(pack: GuidanceRegistry['packs'][number], sectionId: string): string {
  const dump = packDump(pack, true).get('sections') as readonly PyValue[];
  const found = dump.find((item) => item instanceof Map && item.get('id') === sectionId);
  return pyReprValue(found);
}

