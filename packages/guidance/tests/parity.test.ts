function replayAdapter(replays: Record<string, Replay>): UiUxCompile {
  return (requirement) => {
    const replay = replays[requirement.asset_id];
    if (replay === undefined) throw new Error(`no UI/UX replay for ${requirement.asset_id}`);
    return { ...replay, dump: loads(replay.dump) as PyValue };
  };
}

function compileCase(request: unknown, replays: Record<string, Replay>): ReturnType<typeof compilePromptPackages> {
  const parsed = parse(PROMPT_COMPILER_REQUEST, request);
  return compilePromptPackages(parsed, { registry: REAL, uiux: replayAdapter(replays) });
}

