describe('prompt compiler', () => {
  it('reproduces every terminal and refusal state, byte for byte', () => {
    expect(fixture.compile.length).toBeGreaterThanOrEqual(70);
    const states = new Set<string>();
    for (const c of fixture.compile) {
      const result = compileCase(c.request, c.uiux);
      states.add(result.final_state);
      expect(result.final_state, c.name).toBe(c.expect.final_state);
      expect(result.acceptance.status, c.name).toBe(c.expect.acceptance);
      expect(result.voids, c.name).toEqual(c.expect.voids);
      expect(
        result.prompt_packages.map((p) => ({ package_id: p.package_id, prompt_hash: p.prompt_hash, context_hash: p.context_manifest.context_hash, guidance_hash: p.context_manifest.guidance_hash, validation: p.validation.status, issues: p.validation.issues, prompt_sha256: sha256Text(p.generic_master_prompt) })),
        c.name,
      ).toEqual(c.expect.packages);
      expectStored(result, c.expect.dump, c.name);
    }
    expect([...states].sort()).toEqual(['BLOCKED', 'BRAND_SYSTEM_INCOMPLETE', 'PROMPT_PACKAGE_READY', 'RESEARCH_INCOMPLETE']);
  }, SLOW);

  it('revalidates corrupted prompts: a corrupted exact text blocks, a missing objective repairs', () => {
    for (const c of fixture.validate) {
      const result = compileCase(c.request, c.uiux);
      const pkg = result.prompt_packages[0];
      expect(pkg, c.name).toBeDefined();
      if (pkg === undefined) continue;
      let prompt = c.old === '' ? pkg.generic_master_prompt : pkg.generic_master_prompt.replaceAll(c.old, c.new);
      const specHash = (pkg.ui_ux_design as Map<string, PyValue> | null)?.get('spec_hash');
      if (c.strip_spec_hash && typeof specHash === 'string') prompt = prompt.replaceAll(specHash, '');
      const replay = Object.values(c.uiux)[0];
      const adapter: UiUxCompiled | null = replay === undefined ? null : { ...replay, dump: loads(replay.dump) as PyValue };
      const verdict = validatePromptPackage(pkg.asset_spec, pkg.context_manifest, prompt, pkg.provider_prompts, adapter);
      expect(canonicalJson(verdict), c.name).toBe(c.expect);
    }
  });
});

