function attempt(fn: () => unknown): unknown {
  try {
    fn();
  } catch (error: unknown) {
    return error;
  }
  return undefined;
}

function summarize(issue: ValidationIssue): { loc: ReadonlyArray<string | number>; type: string; msg?: string } {
  return issue.type === 'value_error' ? { loc: issue.loc, type: issue.type, msg: issue.msg } : { loc: issue.loc, type: issue.type };
}

function adapter(replays: Record<string, Replay>): UiUxCompile {
  return (requirement) => {
    const replay = replays[requirement.asset_id];
    if (replay === undefined) throw new Error(`no UI/UX replay for ${requirement.asset_id}`);
    return { ...replay, dump: loads(replay.dump) as PyValue };
  };
}

function expectStored(actual: unknown, stored: Stored, label: string): void {
  const text = canonicalJson(actual);
  if (stored.canonical !== undefined) expect(text, label).toBe(stored.canonical);
  expect(text.length, label).toBe(stored.length);
  expect(sha256Text(text), label).toBe(stored.sha256);
}

/** Floats come back from JSON as plain numbers; compare TS floats by value. */
function plain(value: unknown): unknown {
  if (isPyFloat(value)) return value.value;
  if (Array.isArray(value)) return value.map((item: unknown) => plain(item));
  if (value !== null && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, plain(v)]));
  return value;
}

