describe('request validation', () => {
  it('refuses what Pydantic refuses (loc and type), and refuses its lax coercions', () => {
    expect(fixture.requests.length).toBeGreaterThanOrEqual(25);
    for (const c of fixture.requests) {
      const thrown = attempt(() => parse(PROMPT_FAMILY_REQUEST, c.request));
      if (c.python_accepts && c.lax === true) {
        expect(thrown, `${c.name}: Python accepts, TS refuses`).toBeInstanceOf(ValidationError);
      } else if (c.python_accepts) {
        expect(thrown, c.name).toBeUndefined();
      } else {
        expect(thrown, c.name).toBeInstanceOf(ValidationError);
        expect((thrown as ValidationError).issues.map(summarize), c.name).toEqual(c.error?.errors);
      }
    }
  });

  it('keeps a hook score from becoming observed performance', () => {
    const base = { hook_id: 'h', territory: 't', text: 'x', creative_score: 0.99 };
    expect(parse(HOOK_CANDIDATE, base).status).toBe('CANDIDATE');
    expect(() => parse(HOOK_CANDIDATE, { ...base, status: 'MEASURED', approval_ref: 'a' })).toThrow(ValidationError);
  });
});
