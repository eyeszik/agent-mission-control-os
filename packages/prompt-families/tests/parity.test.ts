describe('prompt family compiler', () => {
  it('reproduces every family result: PROMPT_PACKAGE_READY, BLOCKED, repairs and rejections', () => {
    expect(fixture.compile.length).toBeGreaterThanOrEqual(60);
    const terminals = new Set<string>();
    for (const c of fixture.compile) {
      const request = parse(PROMPT_FAMILY_REQUEST, c.request);
      const result: PromptFamilyResult = compilePromptFamily(request, { registry: REGISTRY, uiux: adapter(c.uiux) });
      terminals.add(result.terminal_state);
      expect(result.terminal_state, c.name).toBe(c.expect.terminal_state);
      expect(result.blocked_reasons, c.name).toEqual(c.expect.blocked_reasons);
      expect(result.compiler_result.final_state, c.name).toBe(c.expect.compiler_state);
      expect(result.instances.map((i) => i.status), c.name).toEqual(c.expect.instance_status);
      expect(result.instances.map((i) => i.repairs), c.name).toEqual(c.expect.repairs);
      expect(result.family_hash, c.name).toBe(c.expect.family_hash);
      expect(result.responsible_functional_roles, c.name).toEqual(c.expect.roles);
      expect(plain(result.evaluation), c.name).toEqual(c.expect.evaluation);
      expectStored(result.ledger, c.expect.ledger, `${c.name} ledger`);
      expectStored(result, c.expect.dump, c.name);
    }
    expect([...terminals].sort()).toEqual(['BLOCKED', 'PROMPT_PACKAGE_READY']);
  }, SLOW);

  it('never leaves a generated-assets or execution state on a result', () => {
    const c = fixture.compile[0];
    expect(c).toBeDefined();
    if (c === undefined) return;
    const result = compilePromptFamily(parse(PROMPT_FAMILY_REQUEST, c.request), { registry: REGISTRY, uiux: adapter(c.uiux) });
    const compiled: PromptCompilerResult = result.compiler_result;
    expect(compiled.generation_firewall).toBe('PROMPT_PACKAGE_READY');
    expect(result.execution_statement).toContain('generates no media');
    expect(JSON.stringify(Object.keys(result))).not.toMatch(/asset_url|generated|published/);
  });
});

