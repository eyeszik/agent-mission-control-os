type Op = Record<string, unknown>;

function runOp(registry: ArtifactRegistry, op: Op): unknown {
  if (op['op'] === 'commit') {
    return serializeVersion(registry.commit({
      branch: op['branch'] as string, status: op['status'] as ArtifactStatus,
      artifact_type: op['artifact_type'] as string, owner_department: op['owner_department'] as string,
      content: decode(op['content']), generation_mode: (op['generation_mode'] as string | null | undefined) ?? null,
      assumptions: (op['assumptions'] as string[] | undefined) ?? [],
      metadata: (op['metadata'] as Record<string, unknown> | undefined) ?? null,
    }));
  }
  if (op['op'] === 'merge') return serializeOutcome(registry.merge(op['incoming'] as string, (op['base'] as string | undefined) ?? MAIN_BRANCH));
  if (op['op'] === 'head') {
    const head = registry.head(op['branch'] as string);
    return head ? serializeVersion(head) : null;
  }
  if (op['op'] === 'lineage') return registry.lineage(op['branch'] as string).map(serializeVersion);
  return registry.branches();
}

function scriptResult(artifactId: string, ops: readonly Op[]): unknown {
  const registry = new ArtifactRegistry(artifactId);
  const steps = ops.map((op) => capture(() => runOp(registry, op)));
  const final = registry.serialize();
  expect(ArtifactRegistry.deserialize(JSON.parse(JSON.stringify(final))).serialize()).toEqual(final);
  expect(registry.allVersions().map(serializeVersion)).toEqual(final.versions);
  return { steps, final };
}

