function decodeFloat(raw: string): number | PyFloat {
  const named: Record<string, number> = { nan: Number.NaN, inf: Infinity, '-inf': -Infinity };
  const value = named[raw] ?? Number(raw);
  return Number.isInteger(value) || Object.is(value, -0) ? new PyFloat(value) : value;
}

function decodeInt(raw: string): number | bigint {
  const value = BigInt(raw);
  const safe = value <= BigInt(Number.MAX_SAFE_INTEGER) && value >= BigInt(Number.MIN_SAFE_INTEGER);
  return safe ? Number(value) : value;
}

function decodeTag(tag: string, raw: string): PyJsonValue {
  if (tag === '$int') return decodeInt(raw);
  if (tag === '$float') return decodeFloat(raw);
  return String.fromCharCode(...raw.split(' ').map((unit) => parseInt(unit, 16)));
}

function decode(node: unknown): PyJsonValue {
  if (Array.isArray(node)) return node.map(decode);
  if (node === null || typeof node !== 'object') return node as PyJsonValue;
  const entries = Object.entries(node);
  const [only] = entries;
  if (entries.length === 1 && only && ['$int', '$float', '$utf16'].includes(only[0])) {
    return decodeTag(only[0], String(only[1]));
  }
  return Object.fromEntries(entries.map(([k, v]) => [k, decode(v)]));
}

