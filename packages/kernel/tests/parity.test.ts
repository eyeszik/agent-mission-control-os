describe('@amc/kernel TypeScript-only rules', () => {
  it('computes SHA-256 test vectors', () => {
    const bytes = (s: string): Uint8Array => Uint8Array.from(s, (ch) => ch.charCodeAt(0));
    expect(sha256Hex(bytes(''))).toBe('e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855');
    expect(sha256Hex(bytes('abc'))).toBe('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
    expect(sha256Hex(bytes('a'.repeat(1000)))).toBe('41edece42d63e8d9bf515a9ba6932e1c20cbc9f5a5d134645adb5db1b9737ea3');
  });

  it('keeps int and integral float distinct and refuses ambiguous numbers', () => {
    expect(pyJsonDumps(2)).toBe('2');
    expect(pyJsonDumps(new PyFloat(2))).toBe('2.0');
    expect(floatRepr(1e16)).toBe('1e+16');
    expect(floatRepr(0.0001)).toBe('0.0001');
    expect(() => pyJsonDumps(2 ** 60)).toThrow(/bigint/);
  });

  it('refuses values Python would pass through default=str', () => {
    expect(() => pyJsonDumps(new Date(0) as unknown as PyJsonValue)).toThrow(KernelTypeError);
    const cyclic: Record<string, PyJsonValue> = {};
    (cyclic as Record<string, unknown>)['self'] = cyclic;
    expect(() => pyJsonDumps(cyclic)).toThrow('Circular reference detected');
  });

  it('fails closed on an unchecked commit status', () => {
    const registry = new ArtifactRegistry('a');
    const input = { branch: 'main', status: 'bogus' as ArtifactStatus, artifact_type: 'copy_variant',
      owner_department: 'copy', content: 'x' };
    expect(() => registry.commit(input)).toThrow("'bogus' is not a valid ArtifactStatus");
    expect(() => deserializeVersion({ ...serializeVersion(registry.commit({ ...input, status: 'draft' })),
      artifact_id: 7 })).toThrow(/artifact_id must be a string/);
  });

  it('treats an absent context fact as unproven', () => {
    expect(releaseGuardFailures(undefined).map((f) => f.code)).toEqual(['approval_missing', 'brand_safety_failed']);
  });
});
