describe('contrast math', () => {
  it('rounds WCAG ratios and APCA Lc identically for every sampled pair', () => {
    expect(tokensFixture.contrast.pairs.length).toBeGreaterThan(10000);
    for (const [fg, bg, ratio, lc] of tokensFixture.contrast.pairs) {
      expect(wcagContrastRatio(fg, bg), `${fg} on ${bg}`).toBe(ratio);
      expect(apcaLc(fg, bg), `${fg} on ${bg}`).toBe(lc);
    }
  }, 60_000);

  it('luminance agrees to within one unit in the last place', () => {
    for (const [hex, value] of tokensFixture.contrast.luminance) {
      expect(Math.abs(relativeLuminance(hex) - value), hex).toBeLessThan(1e-15);
    }
  });
});

describe('token systems', () => {
  it('compile like Python for every sampled brand', () => {
    expect(tokensFixture.tokens.length).toBeGreaterThanOrEqual(200);
    for (const c of tokensFixture.tokens) {
      const brand = c['brand'] === null ? null : BrandContextSchema.parse(c['brand']);
      const genome = {
        hierarchy: 'h', density: c['density'], geometry: 'g', typography: 't', color: 'c', material: 'm',
        motion: 'mo', interaction: 'i', signature: 's', genome_hash: '',
      } as UIUXDesignIR['design_genome'];
      const spec = compileTokenSystem(brand, genome, { includeAi: c['include_ai'] as boolean, includeData: c['include_data'] as boolean });
      const { css, document, ...rest } = spec;
      const expected = c.ok;
      expect({ ...(plain(rest) as Obj), css_sha256: expect.any(String), document_sha256: expect.any(String) }).toEqual({
        ...expected, css_sha256: expect.any(String), document_sha256: expect.any(String),
        ...(expected['css'] === undefined ? {} : { css: undefined, document: undefined }),
      });
      if (expected['css'] !== undefined) {
        expect(css).toBe(expected['css']);
        expect(plain(document)).toEqual(expected['document']);
      }
    }
  }, 60_000);
});

describe('surface and feature inference', () => {
  it('infers the surface', () => {
    for (const c of parity['surface'] as Obj[]) {
      const request = parseUiuxRequest({
        project_ref: 'p', surface: c['surface'], surface_hint: c['surface_hint'], purpose: c['purpose'], primary_task: c['primary_task'],
      });
      const [mode, assumption] = inferSurface(request);
      expect({ mode, assumption }, JSON.stringify(c)).toEqual({ mode: c['mode'], assumption: c['assumption'] });
    }
  });

  it('extracts features and selects principles', () => {
    for (const c of parity['features'] as Obj[]) {
      const features = extractFeatures(c['mode'] as SurfaceMode, c['text'] as string, {
        aiFeatures: c['ai_features'] as boolean | null, rtl: c['rtl'] as boolean,
      });
      expect([...features], JSON.stringify(c)).toEqual(c['features']);
      expect(selectPrinciples(features).map((p) => p.id)).toEqual(c['principles']);
    }
  });

  it('maps asset types to surfaces', () => {
    for (const c of parity['asset_types'] as Obj[]) expect(surfaceForAssetType(c['asset_type'] as string)).toBe(c['surface']);
  });
});

describe('compile_uiux', () => {
  it('reproduces every IR (spec_hash covers all of it)', () => {
    const cases = parity['compile'] as Array<{ request: Json; ok?: Obj; raises?: { error: string } }>;
    expect(cases.length).toBeGreaterThanOrEqual(380);
    for (const c of cases) {
      const label = JSON.stringify(c.request).slice(0, 120);
      if (c.raises !== undefined) {
        expect(() => compileUiux(c.request), label).toThrow();
        continue;
      }
      const ir = compileUiux(c.request);
      const expected = c.ok as Obj;
      expect(ir.spec_hash, label).toBe(expected['spec_hash']);
      expect(ir.design_genome.genome_hash, label).toBe(expected['genome_hash']);
      expect(ir.terminal, label).toBe(expected['terminal']);
      if (expected['ir'] !== undefined) expect(plain(ir), label).toEqual(expected['ir']);
      expect(UIUXDesignIRSchema.safeParse(ir).success, label).toBe(true);
    }
  }, 120_000);

  it('rejects what Python rejects', () => {
    for (const c of parity['invalid'] as Array<Outcome & { name: string; input: Json }>) {
      expectSame(run(() => parseUiuxRequest(c.input)), c, c.name);
    }
  });

  it('refuses what Python accepts in lax mode', () => {
    for (const c of parity['lax_divergences'] as Array<{ request: Json }>) {
      expect(() => parseUiuxRequest(c.request), JSON.stringify(c.request)).toThrow(ValidationError);
    }
  });
});

