interface Outcome {
  readonly ok?: unknown;
  readonly error?: Error;
}

function run(c: FixtureCase): Outcome {
  const handler = HANDLERS[c.call];
  if (handler === undefined) throw new Error(`no handler for ${c.call}`);
  try {
    return { ok: encode(handler(decode(c.args) as Args)) };
  } catch (error) {
    if (error instanceof Error) return { error };
    throw error;
  }
}

const groups = new Map<string, FixtureCase[]>();
for (const c of fixture.cases) groups.set(c.call, [...(groups.get(c.call) ?? []), c]);
const strict = (c: FixtureCase): boolean => c.lax_divergence !== true && c.snap_refusal !== true;

function label(c: FixtureCase, index: number): string {
  return `${c.call} #${index} ${c.note ?? ''}`;
}

describe('fixture shape', () => {
  it('is the recorded protocol and every call has a handler', () => {
    expect(fixture.protocol).toBe('amc-vnexus-core-parity/v1');
    for (const call of groups.keys()) expect(HANDLERS[call], call).toBeDefined();
    expect(fixture.cases.length).toBeGreaterThan(3000);
  });
});

describe.each([...groups.entries()])('%s', (call, cases) => {
  it(`reproduces ${cases.length} Python results and errors exactly`, { timeout: 120_000 }, () => {
    for (const [index, c] of cases.entries()) {
      if (!strict(c)) continue;
      const got = run(c);
      if (c.error !== undefined) {
        expect(got.error, label(c, index)).toBeDefined();
        expect(got.error?.name, label(c, index)).toBe(c.error.type);
        if (c.error.type === 'ValidationError') {
          expect((got.error as ValidationError).customMessages, label(c, index)).toEqual(c.error.custom);
        } else {
          expect(got.error?.message, label(c, index)).toBe(c.error.message);
        }
      } else {
        expect(got.error?.message, label(c, index)).toBeUndefined();
        expect(got.ok, label(c, index)).toEqual(c.ok);
      }
    }
  });
});

describe('Python accepts, TypeScript refuses', () => {
  const lax = fixture.cases.filter((c) => c.lax_divergence === true);

  it('records every lax-mode divergence and refuses each one', () => {
    expect(lax.length).toBeGreaterThanOrEqual(6);
    for (const [index, c] of lax.entries()) {
      const got = run(c);
      expect(got.error, label(c, index)).toBeDefined();
      expect(got.error instanceof ValidationError || got.error instanceof VnexusDivergenceError, label(c, index)).toBe(true);
      expect(c.error, label(c, index)).toBeUndefined();
    }
  });

  it('refuses snap_colours inputs whose Python behaviour (template replacement, Unicode case folding) it cannot reproduce', () => {
    const refusals = fixture.cases.filter((c) => c.snap_refusal === true);
    expect(refusals.length).toBe(3);
    for (const c of refusals) expect(run(c).error, label(c, 0)).toBeInstanceOf(VnexusDivergenceError);
  });

  it('refuses a lone surrogate where Python raises UnicodeEncodeError', () => {
    expect(() => sourceHash('\ud800')).toThrow(PyValueError);
  });

  it('refuses a supersession cycle where Python would loop forever', () => {
    const node = (id: string, next: string): unknown => ({ node_id: id, kind: 'Brand', label: id, valid_from: '2026', superseded_by: next });
    const g = new Graph([parseNode(node('a', 'b')), parseNode(node('b', 'a'))], []);
    expect(() => g.history('a')).toThrow('supersession cycle');
  });
});

