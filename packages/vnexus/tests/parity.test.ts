function decodeFloat(raw: string): CanonicalFloat {
  const named: Record<string, number> = { nan: Number.NaN, inf: Infinity, '-inf': -Infinity };
  return new CanonicalFloat(named[raw] ?? Number(raw));
}

function decode(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(decode);
  if (value === null || typeof value !== 'object') return value;
  const record = value as Record<string, unknown>;
  if (Object.keys(record).length === 1 && typeof record['$f'] === 'string') return decodeFloat(record['$f']);
  return Object.fromEntries(Object.entries(record).map(([k, v]) => [k, decode(v)]));
}

function encode(value: unknown): unknown {
  if (value === undefined || value === null) return null;
  if (value instanceof CanonicalFloat) return { $f: floatRepr(value.value) };
  if (typeof value === 'number') return Number.isFinite(value) ? value : { $f: floatRepr(value) };
  if (Array.isArray(value)) return value.map(encode);
  if (value instanceof Set) return Array.from(value).sort().map(encode);
  if (typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, encode(v)]));
  return value;
}

