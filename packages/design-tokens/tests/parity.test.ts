function themesOf(document: unknown): Record<string, unknown> {
  const ext = isMapping(document) ? document['$extensions'] : null;
  const amc = isMapping(ext) ? ext['amc'] : null;
  const declared = isMapping(amc) ? amc['themes'] : null;
  if (!isMapping(declared)) return {};
  return Object.fromEntries(Object.entries(declared).map(([name, t]) => [name, isMapping(t) ? t['tokens'] : null]));
}

describe('@amc/design-tokens parity with the Python reference', () => {
  it('uses the fixture compiler version', () => {
    expect(fixture.compiler).toBe(COMPILER_VERSION);
    expect(fixture.cases.length).toBeGreaterThan(1000);
  });

  it('reproduces every fixture case, results and errors alike', () => {
    for (const c of fixture.cases) {
      const run = RUNNERS[c.kind];
      expect(run, c.kind).toBeDefined();
      if (run) expect(run(c), `${c.kind}: ${c.name}`).toEqual(c.expect);
    }
  });

  it('covers every supported $type', () => {
    expect([...SUPPORTED_TYPES].sort()).toEqual(
      ['color', 'cubicBezier', 'dimension', 'duration', 'fontFamily', 'fontWeight', 'number'],
    );
  });
});

describe('the real token source', () => {
  it('compiles apps/web/tokens/amc.tokens.json read from disk to the Python CSS byte-for-byte', () => {
    const document = parseTokenJson(realSourceText);
    const [, css] = compileCss(document, {
      prefix: 'amc', tiered: true, sourceLabel: 'apps/web/tokens/amc.tokens.json', themes: themesOf(document),
    });
    const real = fixture.cases[0];
    expect(real?.name).toMatch(/^real source/);
    // The Python test asserts this fixture CSS equals apps/web/app/tokens.css on disk
    // (Vitest's CSS pipeline empties `.css?raw` imports, so it is not re-read here).
    expect(css).toBe((real?.expect as { ok: { css: string } }).ok.css);
  });

  it('would change source-sha256 if read with plain JSON.parse (1.0 becomes 1)', () => {
    expect(realSourceText).toMatch(/\b1\.0\b/);
    expect(sourceHash(JSON.parse(realSourceText))).not.toBe(sourceHash(parseTokenJson(realSourceText)));
  });
});

describe('@amc/design-tokens TypeScript-only rules', () => {
  it('reads ints and floats the way json.loads does', () => {
    const parsed = parseTokenJson('{"a": 1.0, "b": 2, "c": 0.5, "d": 12345678901234567890, "e": -0, "f": 1e2}');
    expect(canonicalJson(parsed)).toBe('{"a":1.0,"b":2,"c":0.5,"d":12345678901234567890,"e":0,"f":100.0}');
  });

  it('refuses an ambiguous integral number in the source hash', () => {
    expect(() => sourceHash({ a: 2 ** 60 })).toThrow(TokenAmbiguityError);
    expect(sourceHash({ a: BigInt(2) ** BigInt(60) })).toMatch(/^[0-9a-f]{64}$/);
  });

  it('hashes known SHA-256 vectors', () => {
    const utf8 = (s: string): Uint8Array => new TextEncoder().encode(s);
    expect(sha256Hex(utf8(''))).toBe('e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855');
    expect(sha256Hex(utf8('abc'))).toBe('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
    expect(sha256Hex(utf8('a'.repeat(1000)))).toBe('41edece42d63e8d9bf515a9ba6932e1c20cbc9f5a5d134645adb5db1b9737ea3');
  });
});
