const SAFE = BigInt(Number.MAX_SAFE_INTEGER);

function decodeFloat(raw: string): number | CanonicalFloat {
  const named: Record<string, number> = { nan: Number.NaN, inf: Infinity, '-inf': -Infinity };
  const value = named[raw] ?? Number(raw);
  return Number.isInteger(value) ? new CanonicalFloat(value) : value;
}

/** Fixture tags -> the TS value model ($float -> float, $int -> bigint). */
function decode(node: unknown): unknown {
  if (Array.isArray(node)) return node.map((item: unknown) => decode(item));
  if (!isMapping(node)) return node;
  const entries = Object.entries(node);
  const [only] = entries;
  if (entries.length === 1 && only && only[0] === '$float') return decodeFloat(String(only[1]));
  if (entries.length === 1 && only && only[0] === '$int') return BigInt(String(only[1]));
  return Object.fromEntries(entries.map(([k, v]) => [k, decode(v)]));
}

function tagNumber(value: number): unknown {
  if (Number.isSafeInteger(value)) return value === 0 ? 0 : value;
  return { $float: floatRepr(value) };
}

/** The TS value model -> fixture tags, mirroring the Python `tag`. */
function tag(value: unknown): unknown {
  if (value instanceof CanonicalFloat) return { $float: floatRepr(value.value) };
  if (typeof value === 'number') return tagNumber(value);
  if (typeof value === 'bigint') return value <= SAFE && value >= -SAFE ? Number(value) : { $int: value.toString() };
  if (Array.isArray(value)) return value.map((item: unknown) => tag(item));
  if (isMapping(value)) return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, tag(v)]));
  return value ?? null;
}

function errorOf(err: unknown): unknown {
  if (err instanceof TokenError) {
    const chain = err instanceof TokenCycleError ? [...err.chain] : null;
    return { error: err.name, message: err.message, path: err.path, chain };
  }
  if (err instanceof PythonRuntimeError) return { error: err.pythonType, message: err.message, path: null, chain: null };
  throw err;
}

function outcome(run: () => unknown): unknown {
  try {
    return { ok: run() };
  } catch (err: unknown) {
    return { raises: errorOf(err) };
  }
}

function graphView(graph: TokenGraph): unknown {
  const tokens = [...graph.tokens.values()].map((t) => ({
    path: t.path, type: t.type, value: tag(t.value), css: t.css,
    alias_of: t.aliasOf, description: tag(t.description), tier: t.tier,
  }));
  return { source_hash: graph.sourceHash, tiered: graph.tiered, tokens, flat: Object.fromEntries(flatten(graph)) };
}

function runCompile(c: FixtureCase): unknown {
  const o = c['options'] as CompileOptions;
  const themes = o.themes === null ? null : (decode(o.themes) as Record<string, unknown>);
  return outcome(() => {
    const [graph, compiled] = compileCss(decode(c['document']), {
      prefix: o.prefix, tiered: o.tiered, sourceLabel: o.source_label, themes,
    });
    const css = o.selector === null ? compiled : generateCss(graph, { prefix: o.prefix, sourceLabel: o.source_label, selector: o.selector });
    return { css, graph: graphView(graph) };
  });
}

function runRead(c: FixtureCase): unknown {
  return outcome(() =>
    [...readTokens(decode(c['document'])).values()].map((r) => ({
      path: r.path, value: tag(r.value), declared_type: r.declaredType,
      inherited_type: r.inheritedType, description: tag(r.description),
    })),
  );
}

