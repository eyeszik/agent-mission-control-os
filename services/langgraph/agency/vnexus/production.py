def approved_projection(principal: Principal, brand_id: str, *, scope: Scope, scope_ref: str) -> tuple[GenomeProjection, dict[str, Any]]:
    brand = service.brand_for(principal, brand_id)
    resolution, layers = service.resolve_scope(principal, brand_id, scope=scope, scope_ref=scope_ref)
    if not layers:
        raise service.GenomeBlocked("no approved genome applies to this scope", {"scope": scope.value, "scope_ref": scope_ref})
    if resolution.blocking:
        raise service.GenomeBlocked("the approved genome has blocking findings",
                                    {"blocking": [f.model_dump(mode="json") for f in resolution.blocking]})
    narrowest = layers[-1]
    p = GenomeProjection(resolution, brand_name=brand["display_name"], genome_ref=narrowest.version_id or narrowest.scope_ref)
    meta = {"brand": brand, "layers": [{"scope": layer.scope.value, "scope_ref": layer.scope_ref, "version_id": layer.version_id}
                                       for layer in layers], "constraints": [c.model_dump(mode="json") for c in resolution.constraints]}
    return p, meta


def approved_master(principal: Principal, values: dict[str, Any], projects: set[str]) -> dict[str, Any]:
    """The approved identity master, pinned by sha256 in the genome (``visual.logo.master_artifact`` + ``master_sha256``).

    BOUND when the stored bytes still hash to the pinned value; MISMATCH/UNREADABLE are never replaced by another source.
    """
    import hashlib

    from .brandbook.service import _authorized_master_loader

    ref, pinned = values.get("visual.logo.master_artifact"), values.get("visual.logo.master_sha256")
    if not isinstance(ref, str):
        return {"status": "NONE", "detail": "no approved master artifact in the genome"}
    data = _authorized_master_loader(principal, projects)(ref)
    if data is None:
        return {"status": "UNREADABLE", "detail": f"master artifact {ref} is not readable here"}
    digest = hashlib.sha256(data).hexdigest()
    if isinstance(pinned, str) and pinned.lower() != digest:
        return {"status": "MISMATCH", "detail": f"master {ref} bytes {digest[:16]} differ from the pinned {pinned[:16]}"}
    out = {"status": "BOUND", "detail": f"master {ref} sha256 {digest[:16]}" + ("" if pinned else " (no pinned hash in genome)"),
           "artifact_id": ref, "sha256": digest}
    if data.lstrip()[:1] == b"<":
        out["_svg"] = data.decode("utf-8", errors="replace")
    return out


def link_output(principal: Principal, brand_id: str, *, label: str, kind: NodeKind, ref: str, attributes: dict[str, Any],
                genome_version_id: Optional[str], job_id: Optional[str]) -> str:
    """Asset/Experience node derived from the genome version node and generated by the job node."""
    with transaction(write=True) as conn:
        nodes, _ = db.load_graph(conn, brand_id, lock=True)
        current = {(n["kind"], (n["attributes"] or {}).get("ref")): n for n in nodes if n["valid_to"] is None}
        attrs = {"ref": ref, **attributes}
        node = db.insert_node(tenant_id=principal.tenant_id, brand_id=brand_id, kind=kind.value, label=label, attributes=attrs,
                              content_hash=node_hash(kind, label, attrs), actor=principal.user_id, db=conn)
        gv = current.get((NodeKind.GENOME_VERSION.value, genome_version_id))
        if gv is not None:
            db.insert_edge(tenant_id=principal.tenant_id, brand_id=brand_id, kind=EdgeKind.DERIVED_FROM.value, src=node["node_id"],
                           dst=gv["node_id"], provenance={"genome_version_id": genome_version_id}, actor=principal.user_id, db=conn)
        if job_id:
            job_node = current.get((NodeKind.PROVIDER_JOB.value, job_id))
            if job_node is None:
                job_attrs = {"ref": job_id}
                job_node = db.insert_node(tenant_id=principal.tenant_id, brand_id=brand_id, kind=NodeKind.PROVIDER_JOB.value,
                                          label=f"job {job_id[-8:]}", attributes=job_attrs,
                                          content_hash=node_hash(NodeKind.PROVIDER_JOB, "job", job_attrs), actor=principal.user_id, db=conn)
            db.insert_edge(tenant_id=principal.tenant_id, brand_id=brand_id, kind=EdgeKind.GENERATED_BY.value, src=node["node_id"],
                           dst=job_node["node_id"], provenance={"job_id": job_id}, actor=principal.user_id, db=conn)
    return node["node_id"]


def _run_spec(principal: Principal, project_id: str, spec: identity.OutputSpec, *, run_key: str, depends_on: tuple[str, ...] = ()) -> dict:
    request = MediaRequest(capability=spec.capability, spec=spec.source, width=spec.width, height=spec.height, label=spec.name)
    return fabric_service.execute(principal, project_id, provider_id=identity.PROVIDER_FOR[spec.capability], request=request,
                                  idempotency_key=f"{run_key}:{spec.name}", depends_on=depends_on)


def produce_identity(principal: Principal, brand_id: str, *, scope: Scope, scope_ref: str, project_id: str,
                     deliverables: tuple[str, ...], copy: dict[str, str], run_key: str) -> dict[str, Any]:
    service.authorize(principal, project_id, write=True)
    p, meta = approved_projection(principal, brand_id, scope=scope, scope_ref=scope_ref)
    genome = creative_genome(p, project_id=project_id)
    master_binding = approved_master(principal, p.values, {project_id, meta["brand"]["owner_project_id"]})
    guidelines, guidelines_status = None, None
    if "brand_guidelines" in deliverables:
        from services.langgraph.agency.foundry import compose

        from .brandbook.service import guidelines_for_identity

        ir = compose.mark(genome, size=512)
        mark_svg = identity.transparent_svg(compose.to_svg(ir, genome), ir, genome)
        if master_binding["status"] == "BOUND":
            mark_svg = master_binding.pop("_svg")
        html, width, height, guidelines_status = guidelines_for_identity(
            p.values, brand_name=p.brand_name, brand_id=brand_id, genome_ref=p.genome_ref, resolution_hash=p.resolution_hash,
            mark_svg=mark_svg)
        guidelines = (html, width, height)
    outputs, irs = identity.specs(genome, deliverables, copy=copy, constraints=meta["constraints"], genome_ref=p.genome_ref,
                                  guidelines=guidelines)
    results, validations = [], []
    master_binding.pop("_svg", None)
    if master_binding["status"] != "NONE":
        validations.append({"output": "identity master", "check": "master_binding", "passed": master_binding["status"] == "BOUND",
                            "status": "PASSED" if master_binding["status"] == "BOUND" else "FAILED", "severity": "ERROR",
                            "detail": master_binding["detail"]})
    if guidelines_status is not None:
        validations.append({"output": "brand-guidelines.pdf", "check": "guidelines_completeness",
                            "passed": guidelines_status == "READY", "status": "PASSED" if guidelines_status == "READY" else "FAILED",
                            "severity": "WARNING", "detail": f"brand book status {guidelines_status}: gaps are labelled in the "
                                                             "document; build it in /vnexus brand book for the full gap report"})
    for spec in outputs:
        job = _run_spec(principal, project_id, spec, run_key=run_key)
        art = job.get("artifact") or {}
        entry = {"deliverable": spec.deliverable, "name": spec.name, "capability": spec.capability.value, "job_id": job["job_id"],
                 "state": job["state"], "error": job.get("error"), "artifact_id": art.get("artifact_id"), "sha256": art.get("sha256"),
                 "claimable_as_generated": fabric_service.public(job)["claimable_as_generated"]}
        if job["state"] == "QC_PASSED" and art.get("artifact_id"):
            entry["graph_node"] = link_output(principal, brand_id, label=spec.name, kind=NodeKind.ASSET, ref=art["artifact_id"],
                                              attributes={"deliverable": spec.deliverable, "sha256": art["sha256"], "mime": art["mime"]},
                                              genome_version_id=p.genome_ref, job_id=job["job_id"])
        results.append(entry)
        if spec.capability is Capability.VECTOR_SVG:
            validations.append({"output": spec.name, **identity.palette_check(spec.source["svg"], genome)})
        if spec.transparent and job["state"] == "QC_PASSED":
            from services.langgraph.agency.foundry.studio import observe
            from services.langgraph.api.routes._project_common import storage_adapter

            png, _ = observe(art["artifact_id"], storage_adapter())
            validations += [{"output": spec.name, **identity.transparency(png)}, {"output": spec.name, **identity.optical_centre(png)}]
    for key, ir in irs.items():
        validations.append({"output": key, **identity.text_contrast(ir, genome)})
        if ir.kind == "poster":
            margin = next((s.safe_margin for s in outputs if s.deliverable == key.split(":")[0]), 0.06)
            validations.append({"output": key, **identity.safe_area(ir, margin)})
            validations.append({"output": key, **identity.crop_behavior(ir, 1.0)})
    if "logo_mark" in deliverables:
        with tempfile.TemporaryDirectory(prefix="amc-vnexus-minrep-") as work:
            from services.langgraph.agency.foundry import compose

            validations.append({"output": "logo_mark", **identity.min_reproduction(compose.to_svg(compose.mark(genome, size=256), genome),
                                                                                  work=Path(work))})
    if "icon_family" in deliverables:
        icons = [s.source["svg"] for s in outputs if s.deliverable == "icon_family"]
        validations.append({"output": "icon_family", **identity.stroke_consistency(icons)})
    failed = [v for v in validations if v["status"] == "FAILED" and v["severity"] == "ERROR"]
    report = {"kind": "identity", "genome_ref": p.genome_ref, "resolution_hash": p.resolution_hash, "creative_genome_hash": genome.content_hash,
              "outputs": results, "validations": validations, "genome_trace": p.trace(),
              "master_binding": {k: v for k, v in master_binding.items() if not k.startswith("_")},
              "status": "VERIFIED" if all(r["state"] == "QC_PASSED" for r in results) and not failed else "INCOMPLETE",
              "human_review_required": ["visual coherence", "distinctiveness", "fitness for the brief"]}
    report["report_hash"] = canonical_hash(report)
    return report


def produce_experience(principal: Principal, brand_id: str, *, scope: Scope, scope_ref: str, project_id: str,
                       request: experience.ExperienceRequest) -> dict[str, Any]:
    service.authorize(principal, project_id, write=True)
    p, _ = approved_projection(principal, brand_id, scope=scope, scope_ref=scope_ref)
    compiled = experience.compile_experience(p, request, project_id=project_id)
    from services.langgraph.agency.foundry.studio import store
    from services.langgraph.api.routes._project_common import storage_adapter

    adapter = storage_adapter()
    stem = f"vnexus-experience-{compiled['package']['package_hash'][:12]}"
    stored = {"package": store(principal, project_id, f"{stem}.json", json.dumps(compiled["package"], indent=2, sort_keys=True).encode(),
                               mime="application/json", artifact_type="product_spec", subtype="vnexus_experience_package",
                               adapter=adapter, v2={"provenance_ref": f"vnexus:{p.genome_ref}"})}
    stored["tokens_css"] = store(principal, project_id, f"{stem}.tokens.css", compiled["tokens_css"].encode(), mime="text/css",
                                 artifact_type="design_token_set", subtype="css", adapter=adapter,
                                 depends_on=(stored["package"]["artifact_id"],))
    verification: dict[str, Any] = {"status": "NOT_APPLICABLE"}
    if compiled["html"] is not None:
        stored["html"] = store(principal, project_id, f"{stem}.html", compiled["html"].encode(), mime="text/html",
                               artifact_type="website_lockup_spec", subtype="experience_twin", adapter=adapter,
                               depends_on=(stored["package"]["artifact_id"],))
        with tempfile.TemporaryDirectory(prefix="amc-vnexus-exp-") as work:
            first = request.content[0].title if request.content else "Offering"
            verification = experience.verify(compiled["html"], compiled["genome"], out_dir=Path(work), first_offering=first)
        report_bytes = json.dumps(verification, indent=2, sort_keys=True).encode()
        stored["verification"] = store(principal, project_id, f"{stem}.verification.json", report_bytes, mime="application/json",
                                       artifact_type="qa_report", subtype="experience_evaluation", adapter=adapter,
                                       depends_on=(stored["html"]["artifact_id"],))
    node = link_output(principal, brand_id, label=f"{request.target.value.lower()} experience", kind=NodeKind.EXPERIENCE,
                       ref=stored["package"]["artifact_id"], attributes={"package_hash": compiled["package"]["package_hash"],
                                                                         "verification": verification.get("status")},
                       genome_version_id=p.genome_ref, job_id=None)
    return {"kind": "experience", "package": compiled["package"], "stored": {k: v["artifact_id"] for k, v in stored.items()},
            "verification": verification, "graph_node": node,
            "status": "VERIFIED" if verification.get("status") == "PASSED" else ("SPEC_ONLY" if compiled["html"] is None else "INCOMPLETE")}


def art_direction(principal: Principal, brand_id: str, *, scope: Scope, scope_ref: str, project_id: str,
                  request: art_director.ArtDirectionRequest) -> dict[str, Any]:
    service.authorize(principal, project_id, write=True)
    p, _ = approved_projection(principal, brand_id, scope=scope, scope_ref=scope_ref)
    brief = art_director.compile_brief(p, request)
    from services.langgraph.agency.foundry.studio import store
    from services.langgraph.api.routes._project_common import storage_adapter

    head = store(principal, project_id, f"vnexus-art-direction-{brief['brief_hash'][:12]}.json",
                 json.dumps(brief, indent=2, sort_keys=True).encode(), mime="application/json", artifact_type="design_brief",
                 subtype="vnexus_art_direction", adapter=storage_adapter(), v2={"provenance_ref": f"vnexus:{p.genome_ref}"})
    node = link_output(principal, brand_id, label=f"art direction: {request.objective[:60]}", kind=NodeKind.DESIGN_DECISION,
                       ref=head["artifact_id"], attributes={"brief_hash": brief["brief_hash"], "claim_counts": brief["claim_counts"]},
                       genome_version_id=p.genome_ref, job_id=None)
    return {"brief": brief, "artifact_id": head["artifact_id"], "graph_node": node}


def produce_video(principal: Principal, brand_id: str, *, scope: Scope, scope_ref: str, project_id: str, brief: video.VideoBrief,
                  run_key: str) -> dict[str, Any]:
    service.authorize(principal, project_id, write=True)
    p, _ = approved_projection(principal, brand_id, scope=scope, scope_ref=scope_ref)
    genome = creative_genome(p, project_id=project_id)
    plan = video.plan(brief, genome)
    shots = [video.Shot.model_validate(s) for s in plan["shot_list"]]
    frames, timeline = video.frames_for(shots, genome, width=brief.width, height=brief.height, fps=brief.fps)
    stages: dict[str, Any] = {k: plan[k] for k in ("script", "storyboard", "shot_list", "asset_plan", "animation_plan")}
    blocked = []
    for shot in shots:
        if shot.path == "B_AI_PROVIDER":
            cap = Capability.TEXT_TO_VIDEO if shot.kind is video.ShotKind.LIVE_ACTION else Capability.TEXT_TO_IMAGE
            provider = "hosted.text_to_video" if cap is Capability.TEXT_TO_VIDEO else "hosted.text_to_image"
            job = fabric_service.execute(principal, project_id, provider_id=provider,
                                         request=MediaRequest(capability=cap, spec={"shot": shot.model_dump(mode="json")},
                                                              width=brief.width, height=brief.height, label=f"shot {shot.shot_id}"),
                                         idempotency_key=f"{run_key}:shot:{shot.shot_id}")
            blocked.append({"shot_id": shot.shot_id, "kind": shot.kind.value, "job_id": job["job_id"], "state": job["state"],
                            "error": job.get("error")})
    master = fabric_service.execute(principal, project_id, provider_id="local.svg_motion",
                                    request=MediaRequest(capability=Capability.MOTION_MP4, spec={"frames": frames, "fps": brief.fps},
                                                         width=brief.width, height=brief.height, label="procedural master"),
                                    idempotency_key=f"{run_key}:master")
    stages["render_jobs"] = {"master_job": master["job_id"], "state": master["state"], "error": master.get("error"), "blocked_shots": blocked}
    stages["compositing"] = {"method": "SVG layer stack per frame; no separate compositor", "frames": len(frames), "timeline": timeline}
    from services.langgraph.agency.foundry.studio import observe, store
    from services.langgraph.api.routes._project_common import storage_adapter

    adapter = storage_adapter()
    art = master.get("artifact") or {}
    audio: dict[str, Any] = {"status": "SILENT", "reason": "no audio supplied; nothing generated"}
    deliverables: dict[str, Any] = {}
    if master["state"] == "QC_PASSED" and art.get("artifact_id"):
        deliverables["master_silent"] = art["artifact_id"]
        if brief.audio_artifact_id:
            audio = _mux(principal, project_id, brief, art["artifact_id"], adapter, observe, store)
            if audio.get("artifact_id"):
                deliverables["master_with_audio"] = audio["artifact_id"]
        vtt = video.webvtt(timeline, shots)
        deliverables["captions"] = store(principal, project_id, f"vnexus-video-{master['job_id'][-12:]}.vtt", vtt.encode(), mime="text/vtt",
                                         artifact_type="media_asset", subtype="captions", adapter=adapter,
                                         depends_on=(art["artifact_id"],))["artifact_id"]
        still = fabric_service.execute(principal, project_id, provider_id="local.chromium_raster",
                                       request=MediaRequest(capability=Capability.RASTER_PNG, spec={"svg": frames[-1]}, width=brief.width,
                                                            height=brief.height, label="reduced-motion still"),
                                       idempotency_key=f"{run_key}:still", depends_on=(art["artifact_id"],))
        if still["state"] == "QC_PASSED":
            deliverables["reduced_motion_still"] = (still.get("artifact") or {}).get("artifact_id")
        link_output(principal, brand_id, label="video master", kind=NodeKind.ASSET, ref=art["artifact_id"],
                    attributes={"sha256": art["sha256"], "plan_hash": plan["plan_hash"]}, genome_version_id=p.genome_ref,
                    job_id=master["job_id"])
    stages["audio"] = audio
    stages["quality_control"] = master.get("qc") or {}
    ready = master["state"] == "QC_PASSED" and "captions" in deliverables and "reduced_motion_still" in deliverables
    stages["master"] = {"status": "MASTER_READY" if ready else "INCOMPLETE", "deliverables": deliverables,
                        "procedural_only": bool(blocked), "blocked_shots": [b["shot_id"] for b in blocked]}
    return {"kind": "video", "plan_hash": plan["plan_hash"], "stages": stages, "genome_ref": p.genome_ref,
            "status": stages["master"]["status"], "label": "synthetic procedural animation; not filmed footage"}


def _mux(principal: Principal, project_id: str, brief: video.VideoBrief, master_id: str, adapter: Any, observe: Any, store: Any) -> dict[str, Any]:
    from services.langgraph.persistence.agency_kernel import get_artifact

    if not brief.audio_licence.strip():
        return {"status": "REFUSED", "reason": "audio supplied without a licence record"}
    head = get_artifact(brief.audio_artifact_id)
    if head is None or head.get("project_id") != project_id:
        return {"status": "REFUSED", "reason": "audio artifact not found in this project"}
    audio_bytes, _ = observe(brief.audio_artifact_id, adapter)
    video_bytes, _ = observe(master_id, adapter)
    with tempfile.TemporaryDirectory(prefix="amc-vnexus-mux-") as work:
        w = Path(work)
        (w / "in.mp4").write_bytes(video_bytes)
        (w / "audio.bin").write_bytes(audio_bytes)
        result = video.mux_audio(w / "in.mp4", w / "audio.bin", w / "out.mp4")
        if result["status"] != "SUCCEEDED":
            return {"status": "FAILED", "reason": result.get("stderr") or result.get("reason")}
        probe = video.probe_streams(w / "out.mp4")
        kinds = sorted({s.get("codec_type") for s in probe.get("streams", [])})
        if kinds != ["audio", "video"]:
            return {"status": "FAILED", "reason": f"muxed file streams: {kinds}"}
        stored = store(principal, project_id, f"vnexus-video-{master_id[-12:]}-audio.mp4", (w / "out.mp4").read_bytes(), mime="video/mp4",
                       artifact_type="media_asset", subtype="video_master_audio", adapter=adapter, depends_on=(master_id, brief.audio_artifact_id),
                       v2={"audio_licence": brief.audio_licence})
    return {"status": "MUXED", "artifact_id": stored["artifact_id"], "streams": kinds, "licence": brief.audio_licence}


