"""VNEXUS production runner: approved genome -> fabric jobs -> stored, verified, graph-linked deliverables.

Production starts only from an *authoritative* resolution: at least one
approved layer, no blocking constraint findings. Drafts and branches can be
previewed elsewhere but never produce deliverables.

Each output is a fabric job with an idempotency key derived from the run key,
so a retried request replays instead of rendering twice. Every stored output
is linked into the brand graph (Asset -DERIVED_FROM-> GenomeVersion,
Asset -GENERATED_BY-> ProviderJob) so a later genome change reaches it through
impact analysis.
"""

