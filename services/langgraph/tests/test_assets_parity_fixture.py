"""Brand SVG renderer cross-language parity fixture (Python is the reference).

`packages/assets/tests/fixtures/assets-parity.json` records renderer inputs and
the exact SVG text `agency/assets.py` returns for each. `@amc/assets` must
reproduce every entry byte-for-byte. This test checks the stored entries still
match Python, so a change to `assets.py` fails here before it silently breaks
the TypeScript twin.

It also owns `packages/assets/src/python-unicode.ts`: Python's `str.split()`
whitespace set and the code points Python's `str.upper()` changes, so the
initials never depend on the JS engine's Unicode version. The fixture carries
Python's full non-identity `upper()` map for an exhaustive check on the TS side.

Regenerate both with AMC_REGENERATE_FIXTURES=1. All brand names are fictional.
"""
from __future__ import annotations

import json
import os
import random
import unicodedata
from pathlib import Path
from typing import Any, Callable

from services.langgraph.agency.assets import (
    render_background_pattern_svg,
    render_hero_svg,
    render_logo_svg,
)

PACKAGE = Path(__file__).resolve().parents[3] / "packages/assets"
FIXTURE = PACKAGE / "tests/fixtures/assets-parity.json"
UNICODE_MODULE = PACKAGE / "src/python-unicode.ts"
RENDERERS: dict[str, Callable[..., str]] = {
    "logo": render_logo_svg,
    "pattern": render_background_pattern_svg,
    "hero": render_hero_svg,
}
CODE_POINTS = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]


def _ranges(code_points: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in code_points:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def _space() -> list[int]:
    return [cp for cp in CODE_POINTS if chr(cp).isspace()]


def _upper_map() -> dict[str, str]:
    return {str(cp): chr(cp).upper() for cp in CODE_POINTS if chr(cp).upper() != chr(cp)}


def _render_ranges(name: str, ranges: list[tuple[int, int]]) -> list[str]:
    lines = [f"export const {name}: readonly CodePointRange[] = ["]
    for i in range(0, len(ranges), 4):
        lines.append("  " + " ".join(f"[0x{lo:x}, 0x{hi:x}]," for lo, hi in ranges[i:i + 4]))
    return lines + ["];", ""]


def render_unicode_module() -> str:
    upper = sorted(int(cp) for cp in _upper_map())
    return "\n".join([
        "// GENERATED by services/langgraph/tests/test_assets_parity_fixture.py from Python's str methods.",
        "// Do not edit by hand. Regenerate with AMC_REGENERATE_FIXTURES=1.",
        "",
        "export type CodePointRange = readonly [number, number];",
        "",
        f"export const PYTHON_UNIDATA_VERSION = '{unicodedata.unidata_version}';",
        "",
        "/** Code points where Python's str.isspace() is true (the str.split() separators). */",
        *_render_ranges("SPACE_RANGES", _ranges(_space())),
        "/** Code points whose Python str.upper() differs from the code point itself. */",
        *_render_ranges("UPPER_CASED_RANGES", _ranges(upper)),
    ])


COLORS = ["#0B1F3A", "#F2C14E", "#FFFFFF", "rgb(1, 2, 3)", "url(#x)", '"><script>', "", "red\nblue"]

HANDWRITTEN_NAMES = [
    "Northwind Atelier", "acme", "", "   ", "\t\n", "ß-studio ßeta", "ŉorth wind", "ﬁne ﬂow", "ǆungle ǳone",
    "ımza İstanbul", "élan vital", "ωmega σigma", "𐐨eseret 𐐩lphabet", "😀 smile co", "中文 品牌", "١ brand",
    "ǅ tri", "́combining start", "a\x1cb\x1dc", "a\x85b", "a b", "a　b", "a﻿b", "a​b",
    "a b", "x᠎y", "  leading and trailing  ", "Tom & Jerry's <Co>", '"Quoted" Brand', "one two three four",
    "line\nbreak", "line\n        indented", "line\n    four", "line\n\tTab", "line\n   \nblank", "cr\rreturn",
    "ƛ lambda", "ɤ rams horn", "ᲊ cyrillic", "ꟍ latin", "\U00010d70 garay",
]

ALPHABET = ["a", "Z", "ß", "ŉ", "ﬁ", "ı", "i", "é", "σ", "ǆ", "𐐨", "😀", "中", " ", "  ", "\t", "\n", "\n  ",
            "\n        ", "\x1c", "\x85", "　", "﻿", "&", "<", ">", '"', "'", "·", "\r", " "]


def _random_text(r: random.Random) -> str:
    return "".join(r.choice(ALPHABET) for _ in range(r.randint(0, 10)))


def _kwargs(kind: str, name: str, r: random.Random) -> dict[str, Any]:
    base: dict[str, Any] = {
        "brand_name": name, "primary": r.choice(COLORS), "secondary": r.choice(COLORS), "surface": r.choice(COLORS),
    }
    if kind == "logo":
        base["tagline"] = r.choice([None, "", "Make it plain", "tag & line", "multi\nline tag", _random_text(r)])
    if kind == "hero":
        base.update(headline=r.choice(["Brand <new>", "two\nlines", _random_text(r)]),
                    audience=r.choice(["founders & makers", "", _random_text(r)]), accent=r.choice(COLORS))
    return base


def _case(kind: str, kwargs: dict[str, Any]) -> dict[str, Any]:
    return {"kind": kind, "kwargs": kwargs, "output": RENDERERS[kind](**kwargs)}


def build_fixture() -> dict[str, Any]:
    r = random.Random(8080)
    cases = [_case(kind, _kwargs(kind, name, r)) for name in HANDWRITTEN_NAMES for kind in RENDERERS]
    cases += [_case("logo", {"brand_name": "Plain", "primary": "#000", "secondary": "#111", "surface": "#fff"})]
    for i in range(240):
        kind = list(RENDERERS)[i % 3]
        cases.append(_case(kind, _kwargs(kind, _random_text(r), r)))
    return {
        "protocol": "AMC-ASSETS-PARITY-1",
        "unidata_version": unicodedata.unidata_version,
        "cases": cases,
        "space": _space(),
        "upper": _upper_map(),
    }


def _regenerate() -> bool:
    return os.environ.get("AMC_REGENERATE_FIXTURES") == "1"


def _load() -> dict[str, Any]:
    if _regenerate() or not FIXTURE.exists():
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(json.dumps(build_fixture(), indent=1, ensure_ascii=True) + "\n")
    return json.loads(FIXTURE.read_text())


def test_unicode_module_matches_python_str_methods() -> None:
    rendered = render_unicode_module()
    if _regenerate() or not UNICODE_MODULE.exists():
        UNICODE_MODULE.write_text(rendered)
    assert UNICODE_MODULE.read_text() == rendered


def test_fixture_cases_match_python_reference() -> None:
    fixture = _load()
    assert len(fixture["cases"]) > 300
    for case in fixture["cases"]:
        assert RENDERERS[case["kind"]](**case["kwargs"]) == case["output"], case["kwargs"]


def test_fixture_unicode_tables_match_python() -> None:
    fixture = _load()
    assert fixture["unidata_version"] == unicodedata.unidata_version
    assert fixture["space"] == _space()
    assert fixture["upper"] == _upper_map()
