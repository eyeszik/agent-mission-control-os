def book_summary(book: compiler.BookPackage, spec: dict[str, Any], *, full: bool) -> dict[str, Any]:
    out: dict[str, Any] = {
        "package_hash": book.package_hash, "context_hash": spec_context_hash(spec), "status": book.status, "gap_count": len(book.gaps),
        "pages": [[p.page_id, p.status, p.dependency_hash, p.package_hash, len(p.gaps), len(p.copy_blocks), len(p.blocks)] for p in book.pages],
        "prompts_sha256": sha("\x00".join(compiler.standalone_prompt(p) for p in book.pages)),
    }
    if full:
        out["package"] = dump(book)
        out["prompts"] = [compiler.standalone_prompt(p) for p in book.pages]
    return out


