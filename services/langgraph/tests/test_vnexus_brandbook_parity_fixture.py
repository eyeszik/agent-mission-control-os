def mark(kind: str, **kw: Any) -> dict[str, Any]:
    base = {"kind": kind, "sha256": None, "svg": None, "source": "test mark", "approved": False}
    if kind in ("VECTOR", "PROPOSED_CONCEPT", "RASTER_IN_SVG"):
        svg = kw.get("svg") or (SVG_RASTER if kind == "RASTER_IN_SVG" else SVG_A)
