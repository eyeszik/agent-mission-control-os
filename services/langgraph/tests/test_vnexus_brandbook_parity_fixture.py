# --- Python's own character tables -------------------------------------------------------------------------------


def _ranges(code_points: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in code_points:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def _matching(pattern: str) -> list[int]:
    rx = re.compile(pattern)
    return [cp for cp in range(0x110000) if rx.fullmatch(chr(cp))]


def _render_ranges(name: str, ranges: list[tuple[int, int]]) -> list[str]:
    lines = [f"export const {name}: readonly CodePointRange[] = ["]
    for i in range(0, len(ranges), 4):
        lines.append("  " + " ".join(f"[0x{lo:x}, 0x{hi:x}]," for lo, hi in ranges[i:i + 4]))
    return lines + ["];", ""]


def _linear(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def _linear_table() -> list[str]:
    """Python's `**` (libm pow) differs from V8's by one ulp for some channels, so the 256 linearized sRGB values are copied."""
    table = [_linear(i / 255) for i in range(256)]
    for i in range(0, 256, 17):
        grey = f"#{i:02x}{i:02x}{i:02x}"
        assert relative_luminance(grey) == 0.2126 * table[i] + 0.7152 * table[i] + 0.0722 * table[i], "table formula drifted"
    lines = ["/** `lin(i / 255)` from ui_ux/tokens.relative_luminance for every 8-bit channel value i, as Python computes it. */",
             "export const SRGB_LINEAR: readonly number[] = ["]
    for i in range(0, 256, 4):
        lines.append("  " + " ".join(f"{repr(v)}," for v in table[i:i + 4]))
    return lines + ["];", ""]


def unicode_module() -> str:
    space = [cp for cp in range(0x110000) if chr(cp).isspace()]
    assert space == _matching(r"\s"), "str.isspace() and re \\s differ"
    isdigit = [cp for cp in range(0x110000) if chr(cp).isdigit()]
    lines = [
        "// GENERATED by services/langgraph/tests/test_vnexus_brandbook_parity_fixture.py from Python's re engine.",
        "// Do not edit by hand. Regenerate with AMC_REGENERATE_FIXTURES=1.",
        "",
        "export type CodePointRange = readonly [number, number];",
        "",
        f"export const PYTHON_UNIDATA_VERSION = '{unicodedata.unidata_version}';",
        "",
        "/** Code points Python's `\\w` matches in a str pattern. */",
        *_render_ranges("WORD_RANGES", _ranges(_matching(r"\w"))),
        "/** Code points Python's `\\d` matches in a str pattern (Unicode decimal digits). */",
        *_render_ranges("DECIMAL_RANGES", _ranges(_matching(r"\d"))),
        "/** Code points Python's `\\s` matches in a str pattern (same set as str.isspace()). */",
        *_render_ranges("SPACE_RANGES", _ranges(space)),
        "/** Code points for which Python's str.isdigit() is true. */",
        *_render_ranges("ISDIGIT_RANGES", _ranges(isdigit)),
        *_linear_table(),
    ]
    return "\n".join(lines)


# --- value tags ---------------------------------------------------------------------------------------------------


def enc(v: Any) -> Any:
    if isinstance(v, float):
        return {"$float": repr(v)} if (v.is_integer() or not math.isfinite(v)) else v
    if isinstance(v, (list, tuple)):
        return [enc(x) for x in v]
    if isinstance(v, dict):
        return {k: enc(x) for k, x in v.items()}
    return v


def sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def outcome(fn: Callable[[], Any]) -> dict[str, Any]:
    try:
        return {"ok": enc(fn())}
    except Exception as exc:  # noqa: BLE001 - the fixture records every Python error class and message
        return {"error": {"type": type(exc).__name__, "message": str(exc)}}


def dump(model: Any) -> Any:
    return enc(model.model_dump(mode="json"))


