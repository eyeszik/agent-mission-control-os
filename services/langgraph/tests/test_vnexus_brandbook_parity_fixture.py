def status_cases() -> list[dict[str, Any]]:
    out = []
    for book_status in ("READY", "DRAFT", "BLOCKED", "SPEC_ONLY"):
        for mode in MODES:
            for blocking in (0, 2):
                if mode is Mode.PRODUCTION and blocking:
                    status = "BLOCKED"
                elif book_status == "BLOCKED":
                    status = "BLOCKED"
                elif mode is Mode.PRODUCTION and book_status == "READY":
                    status = "READY_FOR_APPROVAL"
                else:
                    status = "PREVIEW_ONLY" if mode is Mode.PREVIEW else "DRAFT"
                out.append({"book_status": book_status, "mode": mode.value, "blocking": blocking, "status": status})
    return out


def gap_group_cases() -> list[dict[str, Any]]:
    """Transcribes service.gaps_report's grouping (inline there, needs a principal to call)."""
    out = []
