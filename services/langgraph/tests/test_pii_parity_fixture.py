def _random_sanitize_value(r: random.Random, depth: int) -> Any:
    kind = r.randrange(5 if depth < 3 else 3)
    if kind == 0:
        return _random_injection_text(r)
    if kind == 1:
        return r.choice([None, True, 3, 2.5])
    if kind == 2:
        return r.choice(INJECTIONS)
    if kind == 3:
        return [_random_sanitize_value(r, depth + 1) for _ in range(r.randint(0, 3))]
    return {f"k{i}": _random_sanitize_value(r, depth + 1) for i in range(r.randint(0, 3))}


def _b64_case(fragment: str) -> dict[str, Any]:
    try:
        raw = base64.b64decode(fragment, validate=True)
    except (ValueError, binascii.Error):
        return {"fragment": fragment, "ok": False}
    return {"fragment": fragment, "ok": True, "hex": raw.hex()}


def _random_bytes(r: random.Random) -> bytes:
    specials = [0x80, 0xBF, 0xC0, 0xC2, 0xDF, 0xE0, 0xA0, 0xED, 0x9F, 0xEF, 0xBB, 0xF0, 0x90, 0xF4, 0x8F, 0xF5, 0xFF]
    return bytes(r.choice(specials + [r.randrange(256), 0x41]) for _ in range(r.randint(0, 10)))


def _lower_to_ascii() -> list[int]:
    return [cp for cp in range(0x80, 0x110000)
            if not 0xD800 <= cp <= 0xDFFF and (low := chr(cp).lower()).isascii() and low != chr(cp)]


