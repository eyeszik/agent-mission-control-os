def _encode(r: random.Random, text: str) -> str:
    kind = r.randrange(6)
    if kind == 0:
        return base64.b64encode(text.encode()).decode()
    if kind == 1:
        return quote(text, safe="")
    if kind == 2:
        return quote(quote(text, safe=""), safe="")
    if kind == 3:
        return quote(quote(quote(text, safe=""), safe=""), safe="")
    if kind == 4:
        raw = bytearray(text.encode())
        raw.insert(r.randrange(len(raw) + 1), r.choice([0xFF, 0x80, 0xC3, 0xE2]))
        return base64.b64encode(bytes(raw)).decode()
    return "".join(f"%{b:02x}" for b in text.encode())


def _random_text(r: random.Random) -> str:
    pieces = []
    for _ in range(r.randint(1, 5)):
        pool = r.randrange(4)
        piece = r.choice(_secrets(r)) if pool == 0 else r.choice(NEAR_MISSES) if pool == 1 else r.choice(FILLERS)
        if pool == 3:
            piece = _tok(r, r.randint(1, 30), ALNUM + "+/=")
        if piece and r.random() < 0.3:
            piece = _encode(r, piece)
        pieces.append(piece)
    return r.choice(["", " ", "\n", "-"]).join(pieces)


