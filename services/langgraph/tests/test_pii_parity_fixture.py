"""PII / sanitize cross-language parity fixture (Python is the reference).

`packages/pii/tests/fixtures/pii-parity.json` records inputs and what
`security/pii.py` and `security/sanitize.py` (and the codecs they lean on)
return for each. `@amc/pii` must reproduce every entry. This test checks the
stored entries still match Python, so a change to either module fails here
before it silently breaks the TypeScript twin.

It also owns `packages/pii/src/python-unicode.ts`: the tables of Python's
`\\w`, `\\d`, `\\s` and IGNORECASE letter equivalents, read from Python's own
`re` engine. The TypeScript regexes are built from them instead of JS's
narrower escapes, so the JS engine's Unicode version never decides a match.

Regenerate both with AMC_REGENERATE_FIXTURES=1. All values are fictional.
"""
