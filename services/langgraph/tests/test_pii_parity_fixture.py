def _codec_sections(r: random.Random, texts: list[str]) -> dict[str, Any]:
    fragments = ["Q" * n + "=" * p for n in range(24, 32) for p in range(3)]
    fragments += [m.group(0) for t in texts for m in _BASE64_FRAGMENT.finditer(t)]
    quoted = [_random_text(r) for _ in range(100)] + ["".join(f"%{b:02X}" for b in _random_bytes(r)) for _ in range(100)]
    quoted += ["é%E2%82%ACé", "%e2%82%ac", "%zz%4%", "%%41", "a%2", "%C3%A9%", "中%E4%B8%AD中"]
    utf8 = [_random_bytes(r) for _ in range(300)] + [b"\xef\xbb\xbfA", b"\xef\xbf\xbd", b"\xed\xa0\x80", b"\xf4\x90\x80\x80"]
    return {
        "unquote": [{"text": q, "output": unquote(q, errors="replace")} for q in quoted],
        "base64": [_b64_case(f) for f in dict.fromkeys(fragments)],
        "utf8": [{"hex": b.hex(), "replace": b.decode("utf-8", "replace"), "ignore": b.decode("utf-8", "ignore")}
                 for b in utf8],
        "lower_to_ascii": _lower_to_ascii(),
    }


def build_fixture() -> dict[str, Any]:
    r = random.Random(4242)
    texts, scanner = _scanner_sections(r)
    header = {"protocol": "AMC-PII-PARITY-1", "unidata_version": unicodedata.unidata_version}
    return {**header, **scanner, **_codec_sections(r, texts)}


def _regenerate() -> bool:
    return os.environ.get("AMC_REGENERATE_FIXTURES") == "1"


# Strings longer than CHUNK are stored as {"$s": [chunks]} so no credential-shaped
# run (fictional GitHub-style keys the detector must see) appears contiguously
# in the committed file, where repository secret scanning would flag it.
CHUNK = 8


def _chunk(node: Any) -> Any:
    if isinstance(node, str) and len(node) > CHUNK:
        return {"$s": [node[i:i + CHUNK] for i in range(0, len(node), CHUNK)]}
    if isinstance(node, list):
        return [_chunk(x) for x in node]
    if isinstance(node, dict):
        assert all(len(k) <= CHUNK * 4 for k in node), "long keys are not chunked"
        assert set(node) != {"$s"}, "fixture value collides with the chunk tag"
        return {k: _chunk(v) for k, v in node.items()}
    return node


def _unchunk(node: Any) -> Any:
    if isinstance(node, dict) and set(node) == {"$s"}:
        return "".join(node["$s"])
    if isinstance(node, list):
        return [_unchunk(x) for x in node]
    if isinstance(node, dict):
        return {k: _unchunk(v) for k, v in node.items()}
    return node


def _load() -> dict[str, Any]:
    if _regenerate() or not FIXTURE.exists():
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(json.dumps(_chunk(build_fixture()), indent=1, ensure_ascii=True) + "\n")
    return _unchunk(json.loads(FIXTURE.read_text()))


def _check(section: str, fn: Callable[[dict[str, Any]], bool], minimum: int) -> None:
    cases = _load()[section]
    assert len(cases) >= minimum, section
    for case in cases:
        assert fn(case), (section, case)


def test_unicode_module_matches_python_re() -> None:
    rendered = render_unicode_module()
    if _regenerate() or not UNICODE_MODULE.exists():
        UNICODE_MODULE.write_text(rendered)
    assert UNICODE_MODULE.read_text() == rendered


def test_ignorecase_classes_are_ascii_plus_letter_extras() -> None:
    # pyre.ts builds IGNORECASE classes as the ASCII class plus every letter's extras.
    extras = _ignorecase_extras()
    for body in ("A-Za-z0-9_-", "A-Za-z0-9._~+/-", "A-Za-z0-9-", "abprs"):
        plain = set(_matching(f"[{body}]"))
        folded = {cp for cp in _matching(f"[{body}]", re.IGNORECASE) if cp > 0x7F}
        expected = {cp for letter, cps in extras.items() if ord(letter) in plain for cp in cps}
        assert folded == expected, body


