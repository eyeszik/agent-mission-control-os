# --- Python's own character tables -------------------------------------------

def _ranges(code_points: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in code_points:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def _scalar_values() -> range:
    return range(0x110000)


def render_unicode_module() -> str:
    text = "".join(chr(cp) for cp in _scalar_values() if not 0xD800 <= cp <= 0xDFFF)
    digits = _ranges([ord(m.group(0)) for m in re.finditer(r"\d", text)])
    titles = [(ord(ch), ch.title()) for ch in text if ch.title() != ch.upper()]
    lines = [
        "// GENERATED by services/langgraph/tests/test_design_mode_parity_fixture.py from Python.",
        "// Do not edit by hand. Regenerate with AMC_REGENERATE_FIXTURES=1.",
        "",
        "export type CodePointRange = readonly [number, number];",
        "",
        f"export const PYTHON_UNIDATA_VERSION = '{unicodedata.unidata_version}';",
        "",
        "/** Code points Python's `\\d` matches in a str pattern. */",
        "export const DIGIT_RANGES: readonly CodePointRange[] = [",
    ]
    lines += [f"  [0x{a:x}, 0x{b:x}]," for a, b in digits]
    lines += [
        "];",
        "",
        "/** Characters whose Python `str.title()` differs from `str.upper()` (escaped UTF-16). */",
        "export const TITLE_EXCEPTIONS: ReadonlyMap<number, string> = new Map([",
    ]
    lines += [f"  [0x{cp:x}, {json.dumps(title)}]," for cp, title in titles]
    lines += ["]);", ""]
    return "\n".join(lines)


# --- outcomes -------------------------------------------------------------------

def _validation_messages(exc: ValidationError) -> list[str]:
    return [str(e["ctx"]["error"]) for e in exc.errors() if e["type"] == "value_error"]


def outcome(run: Callable[[], Any]) -> dict[str, Any]:
    try:
        return {"ok": run()}
    except ValidationError as exc:
        return {"raises": {"error": "ValidationError", "value_errors": _validation_messages(exc)}}
    except (ValueError, KeyError) as exc:
        return {"raises": {"error": type(exc).__name__, "message": str(exc)}}


def _lib(raw: dict[str, Any]) -> StyleLibrary:
    return StyleLibrary.model_validate(raw)


