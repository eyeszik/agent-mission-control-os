def _random_selection(r: random.Random, ids: list[str]) -> list[dict[str, Any]]:
    chosen = r.sample(ids, r.randint(1, min(5, len(ids))))
    primary = r.choice([None, *range(len(chosen))])
    out = []
    for index, style_id in enumerate(chosen):
        item: dict[str, Any] = {"style_id": style_id}
        if index == primary:
            item["role"] = "primary"
        elif r.random() < 0.3:
            item["role"] = "secondary"
        if r.random() < 0.85:
            item["strength"] = r.choice([0, 0.0, 0.1, 0.25, 0.3333333333333333, 0.5, 0.75, 0.9, 1, 1.0, r.random()])
        if r.random() < 0.5:
            item["dimensions"] = r.sample(STYLE_DIMENSIONS, r.randint(0, 4))
        if r.random() < 0.3:
            item["locked"] = True
        out.append(item)
    return out


