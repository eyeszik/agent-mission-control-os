"""Design Mode cross-language parity fixture (Python is the reference).

`packages/design-mode/tests/fixtures/design-mode.json` records inputs and what
`agency/design/` returns for each: catalog validation and snapshots, style
lookup, compatibility analysis, per-dimension composition, prompt text,
composition ids and persisted directions, plus every error. `@amc/design-mode`
must reproduce every entry. This test checks the stored entries still match
Python, so a change to Design Mode fails here before it silently breaks the
TypeScript twin.

Errors are stored as ``{"error": <class>, "message": str(exc)}``. A Pydantic
``ValidationError`` is stored as its class plus the messages of its custom
``value_error`` entries (the ones Design Mode raises itself); Pydantic's own
wording for type/range errors is not part of the contract.

``lax_divergences`` lists inputs Pydantic's lax mode accepts (``"0.5"`` or
``True`` for a strength, ``1``/``"yes"`` for a bool, integer-like
``semantic_roles`` keys whose order a JS object would change) that the
TypeScript twin refuses instead of guessing.

It also owns `packages/design-mode/src/python-unicode.ts`: Python's `\\d` set
(style ids are matched with `re`) and the characters whose `str.title()`
differs from `str.upper()` (`str.capitalize()` builds prompt labels).

Regenerate both with AMC_REGENERATE_FIXTURES=1.
"""
