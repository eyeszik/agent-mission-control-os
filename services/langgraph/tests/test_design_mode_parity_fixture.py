def _phrases(r: random.Random, lo: int, hi: int) -> list[str]:
    return [" ".join(r.choice(WORDS) for _ in range(r.randint(1, 3))).strip() for _ in range(r.randint(lo, hi))]


def _random_style(r: random.Random, style_id: str, ids: list[str]) -> dict[str, Any]:
    others = [x for x in ids if x != style_id] + ["PND-01", "PND-02"]
    r.shuffle(others)
    compatible, incompatible = others[: r.randint(0, 3)], others[3: 3 + r.randint(0, 2)]
    roles = {} if r.random() < 0.3 else {r.choice(WORDS) or "role": f"#{r.randrange(16**6):06X}" for _ in range(r.randint(1, 4))}
    return {
        "id": style_id,
        "name": f"Style {style_id} {r.choice(WORDS)}".strip(),
        "category": r.choice(["classical", "modernist", "experimental", "cyber", "lifestyle", "editorial",
                              "illustrative", "material", "interface", "motion"]),
        "description": "synthetic",
        "design_dimensions": r.sample(STYLE_DIMENSIONS, r.randint(1, 5)),
        "physics": {key: _phrases(r, 0, 4) for key in ("lighting", "spatial", "material", "composition", "motion")},
        "palette": {"colors": [f"#{r.randrange(16**6):06x}" for _ in range(r.randint(1, 4))],
                    "semantic_roles": roles, "contrast_notes": _phrases(r, 0, 2)},
        "typography": {"families": _phrases(r, 0, 2), "category": r.choice(["serif", "sans", "mono"]),
                       "weights": ["regular"], "tracking": r.choice([None, "tight", "wide"]),
                       "hierarchy": r.choice([None, "dramatic", "flat"])},
        "prompt_tokens": _phrases(r, 1, 5),
        "negative_tokens": _phrases(r, 0, 3),
        "compatible_with": compatible,
        "incompatible_with": incompatible,
        "recommended_strength": r.choice([0, 0.5, 1, 0.7]),
        "suitable_for": _phrases(r, 0, 2),
        "unsuitable_for": _phrases(r, 0, 2),
        "motion_behavior": _phrases(r, 0, 3),
        "production_notes": _phrases(r, 0, 2),
        "source_version": "synthetic-v1",
        "status": r.choice(STATUSES),
    }


def _synthetic_library(r: random.Random, name: str, size: int) -> dict[str, Any]:
    ids = [f"{p}-{n:02d}" for p, n in zip(r.sample(["AAA", "BBB", "CCC", "DDD", "EEE", "FFF", "GGG"], 7) * 3,
                                           range(1, size + 1))]
    return {"version": name, "styles": [_random_style(r, i, ids) for i in ids]}


def _libraries(r: random.Random) -> dict[str, dict[str, Any]]:
    canonical = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    libraries = {"canonical": canonical}
    for index in range(4):
        libraries[f"synthetic-{index}"] = _synthetic_library(r, f"synthetic-lib-{index}", 10)
    return libraries


def _invalid_libraries(canonical: dict[str, Any]) -> list[tuple[str, Any]]:
    def mutate(fn: Callable[[dict[str, Any]], None]) -> dict[str, Any]:
        raw = copy.deepcopy(canonical)
        fn(raw)
        return raw

    def s0(raw: dict[str, Any]) -> dict[str, Any]:
        return raw["styles"][0]

    return [
        ("empty styles", {"version": "v", "styles": []}),
        ("missing version", {"styles": canonical["styles"]}),
        ("empty version", mutate(lambda raw: raw.update(version=""))),
        ("extra library key", mutate(lambda raw: raw.update(extra=1))),
        ("duplicate ids", mutate(lambda raw: raw["styles"].append(copy.deepcopy(raw["styles"][0])))),
        ("triple duplicates", mutate(lambda raw: raw["styles"].extend([copy.deepcopy(raw["styles"][1])] * 2))),
        ("bad id", mutate(lambda raw: s0(raw).update(id="cls-01"))),
        ("bad ids in two styles", mutate(lambda raw: (s0(raw).update(id="X"), raw["styles"][1].update(id="Y")))),
        ("bad compatible ref", mutate(lambda raw: s0(raw).update(compatible_with=["MOD-07", "nope", "bad"]))),
        ("bad refs both fields", mutate(lambda raw: s0(raw).update(compatible_with=["x"], incompatible_with=["y"]))),
        ("both compatible and incompatible", mutate(lambda raw: s0(raw).update(compatible_with=["LFS-05", "MOD-07"]))),
        ("self reference", mutate(lambda raw: s0(raw).update(compatible_with=["CLS-01"]))),
        ("relation errors in two styles", mutate(lambda raw: (s0(raw).update(compatible_with=["CLS-01"]),
                                                              raw["styles"][1].update(incompatible_with=["CLS-02"])))),
        ("relation error and bad field", mutate(lambda raw: (s0(raw).update(compatible_with=["CLS-01"]),
                                                             raw["styles"][1].update(status="gone")))),
        ("relation error hides duplicate", mutate(lambda raw: (s0(raw).update(compatible_with=["CLS-01"]),
                                                               raw["styles"].append(copy.deepcopy(raw["styles"][2]))))),
        ("unknown dimension", mutate(lambda raw: s0(raw).update(design_dimensions=["smell"]))),
        ("no dimensions", mutate(lambda raw: s0(raw).update(design_dimensions=[]))),
        ("strength above one", mutate(lambda raw: s0(raw).update(recommended_strength=1.5))),
        ("strength below zero", mutate(lambda raw: s0(raw).update(recommended_strength=-0.1))),
        ("no prompt tokens", mutate(lambda raw: s0(raw).update(prompt_tokens=[]))),
        ("no palette colors", mutate(lambda raw: s0(raw)["palette"].update(colors=[]))),
        ("extra style key", mutate(lambda raw: s0(raw).update(mood="x"))),
        ("extra physics key", mutate(lambda raw: s0(raw)["physics"].update(smell=["x"]))),
        ("missing typography category", mutate(lambda raw: s0(raw)["typography"].pop("category"))),
        ("non-string token", mutate(lambda raw: s0(raw).update(prompt_tokens=["a", 3]))),
        ("bad status", mutate(lambda raw: s0(raw).update(status="retired"))),
        ("bad category", mutate(lambda raw: s0(raw).update(category="baroque"))),
        ("empty name", mutate(lambda raw: s0(raw).update(name=""))),
        ("non-object library", ["not", "an", "object"]),
    ]


