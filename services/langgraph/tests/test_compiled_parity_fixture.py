"""Compiled Agency planner + method router cross-language parity fixtures (Python is the reference).

`packages/compiled/tests/fixtures/` holds three JSON fixtures that record calls into
`services/langgraph/agency/compiled` and what Python returned (or raised) for each:

* ``compiled-core.json``    pure building blocks (hashing, ontology, validation, backchain,
                            autonomy, context, decisions, change control, evidence, learning,
                            measurement, date parsing);
* ``compiled-plans.json``   the RoleOS registry (compact), authority bindings, work orders and
                            compiled agency plans (every refusal / blocked path);
* ``compiled-methods.json`` the method catalog, method plans, compiled missions, next steps.

`@amc/compiled` must reproduce every entry exactly, errors included. This test checks the stored
entries still match Python, so a change to the compiled planner fails here before it silently
breaks the TypeScript twin. Regenerate with AMC_REGENERATE_FIXTURES=1. The builders live in the
`_compiled_fixture_*.py` support modules next to this file.

It also owns `packages/compiled/src/python-unicode.ts`: the tables of Python's `str.isspace`,
`str.lower` and `str.casefold`, so the JS engine's Unicode version never decides a result.

Case shape: {"call": name, "args": [...], "ok": result} or
{"call": name, "args": [...], "error": {"type": <exception class>, "message": str(exc)}}.
Pydantic ValidationErrors are stored as {"type": "ValidationError", "locs": [...]}.
"""
from __future__ import annotations

import json
import unicodedata
from pathlib import Path
from typing import Any, Callable

from services.langgraph.tests import _compiled_fixture_core as core
from services.langgraph.tests import _compiled_fixture_methods as methods
from services.langgraph.tests import _compiled_fixture_plans as plans
from services.langgraph.tests._compiled_fixture_support import (
    CORE, METHODS, PACKAGE, PLANS, matches_stored, regenerate, write_or_load,
)

UNICODE_MODULE = PACKAGE / "src/python-unicode.ts"


def _is_surrogate(cp: int) -> bool:
    return 0xD800 <= cp <= 0xDFFF


def _table_lines(name: str, doc: str, entries: list[Any], kind: str) -> list[str]:
    lines = [f"/** {doc} */", f"export const {name}: {kind} = ["]
    for i in range(0, len(entries), 6):
        chunk = entries[i:i + 6]
        if kind.startswith("readonly number"):
            lines.append("  " + " ".join(f"0x{cp:x}," for cp in chunk))
        else:
            lines.append("  " + " ".join(f"[0x{cp:x}, {json.dumps(text)}]," for cp, text in chunk))
    return lines + ["];", ""]


def render_unicode_module() -> str:
    points = [cp for cp in range(0x110000) if not _is_surrogate(cp)]
    space = [cp for cp in points if chr(cp).isspace()]
    # U+03A3 lowercases by context (final sigma); a per-character table cannot, so it is excluded.
    lower = [[cp, chr(cp).lower()] for cp in points if cp != 0x3A3 and chr(cp).lower() != chr(cp)]
    fold = [[cp, chr(cp).casefold()] for cp in points if chr(cp).casefold() != chr(cp)]
    pair = "readonly (readonly [number, string])[]"
    lines = [
        "// GENERATED by services/langgraph/tests/test_compiled_parity_fixture.py from Python's str methods.",
        "// Do not edit by hand. Regenerate with AMC_REGENERATE_FIXTURES=1.",
        "",
        f"export const PYTHON_UNIDATA_VERSION = '{unicodedata.unidata_version}';",
        "",
        *_table_lines("PY_SPACE", "Code points for which Python's `str.isspace()` (and `\\s` in a str pattern) is true.",
                      space, "readonly number[]"),
        *_table_lines("PY_LOWER", "Code points whose Python `str.lower()` differs (U+03A3 excluded: context rule).",
                      lower, pair),
        *_table_lines("PY_CASEFOLD", "Code points whose Python `str.casefold()` differs.", fold, pair),
    ]
    return "\n".join(lines)


def test_unicode_module_matches_python() -> None:
    rendered = render_unicode_module()
    if regenerate() or not UNICODE_MODULE.exists():
        UNICODE_MODULE.write_text(rendered)
    assert UNICODE_MODULE.read_text() == rendered


def _check(path: Path, build: Callable[[], dict[str, Any]], minimum: int) -> None:
    fresh = json.loads(json.dumps(build()))
    write_or_load(path, lambda: fresh)
    matches_stored(path, fresh)
    assert sum(len(v) for v in fresh.values()) >= minimum


def test_core_fixture_matches_python() -> None:
    _check(CORE, core.build_core, 3000)


def test_plans_fixture_matches_python() -> None:
    _check(PLANS, plans.build_plans, 400)


def test_methods_fixture_matches_python() -> None:
    _check(METHODS, methods.build_methods, 300)
