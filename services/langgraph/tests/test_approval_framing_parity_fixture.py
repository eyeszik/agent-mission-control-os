def _fold(r: random.Random, text: str) -> str:
    swaps = {"s": "ſ", "k": "K", "i": "İ", "I": "ı"}
    mode = r.randrange(4)
    if mode == 0:
        return text.upper()
    if mode == 1:
        return "".join(ch.upper() if r.random() < 0.5 else ch for ch in text)
    if mode == 2:
        return "".join(swaps.get(ch, ch) if r.random() < 0.4 else ch for ch in text)
    return text


def _summary(r: random.Random) -> str:
    parts = [r.choice(NEUTRAL)]
    for _ in range(r.randrange(4)):
        pick = r.random()
        source = PHRASES if pick < 0.6 else EVIDENCE if pick < 0.8 else TARGETS
        parts.append(r.choice(NOISE) * r.randrange(2) + _fold(r, r.choice(source)) + r.choice(NOISE) * r.randrange(2))
    r.shuffle(parts)
    return r.choice(["", " ", "  ", "\n", SIGMA]).join(parts)


