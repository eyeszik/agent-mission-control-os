SIGMA, SMALL_SIGMA, FINAL_SIGMA = "Σ", "σ", "ς"


# --- Python's own casing tables ----------------------------------------------

def _code_points() -> list[int]:
    return [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]


def _ranges(code_points: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in code_points:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def _case_ignorable() -> list[int]:
    # Skipped by the backward scan: "xΣ" stays σ, yet "AxΣ" becomes ς.
    return [cp for cp in _code_points()
            if (chr(cp) + SIGMA).lower()[-1] == SMALL_SIGMA
            and ("A" + chr(cp) + SIGMA).lower()[-1] == FINAL_SIGMA]


def _cased_not_ignorable() -> list[int]:
    # The first non-ignorable character before Σ is cased: "xΣ" becomes ς.
    return [cp for cp in _code_points() if (chr(cp) + SIGMA).lower()[-1] == FINAL_SIGMA]


def _lower_map() -> list[tuple[int, str]]:
    return [(cp, chr(cp).lower()) for cp in _code_points()
            if cp != ord(SIGMA) and chr(cp).lower() != chr(cp)]


def _render_ranges(name: str, doc: str, ranges: list[tuple[int, int]]) -> list[str]:
    lines = [f"/** {doc} */", f"export const {name}: readonly CodePointRange[] = ["]
    for i in range(0, len(ranges), 4):
        lines.append("  " + " ".join(f"[0x{lo:x}, 0x{hi:x}]," for lo, hi in ranges[i:i + 4]))
    return lines + ["];", ""]


def _render_lower_map(pairs: list[tuple[int, str]]) -> list[str]:
    lines = ["/** `chr(cp).lower()` for every code point it changes, except U+03A3 (context dependent). */",
             "export const LOWER_MAP: ReadonlyArray<readonly [number, readonly number[]]> = ["]
    cells = [f"[0x{cp:x}, [{', '.join(f'0x{ord(ch):x}' for ch in low)}]]," for cp, low in pairs]
    for i in range(0, len(cells), 4):
        lines.append("  " + " ".join(cells[i:i + 4]))
    return lines + ["];", ""]


def render_casing_module() -> str:
    head = [
        "// GENERATED by services/langgraph/tests/test_approval_framing_parity_fixture.py from str.lower().",
        "// Do not edit by hand. Regenerate with AMC_REGENERATE_FIXTURES=1.",
        "",
        "import type { CodePointRange } from './python-unicode';",
        "",
        f"export const PYTHON_CASING_UNIDATA_VERSION = '{unicodedata.unidata_version}';",
        "",
    ]
    ignorable = "Code points CPython's final-sigma scan skips (case-ignorable)."
    cased = "Non-ignorable code points CPython's final-sigma scan treats as cased."
    return "\n".join(head + _render_ranges("CASE_IGNORABLE_RANGES", ignorable, _ranges(_case_ignorable()))
                     + _render_ranges("CASED_RANGES", cased, _ranges(_cased_not_ignorable()))
                     + _render_lower_map(_lower_map()))


