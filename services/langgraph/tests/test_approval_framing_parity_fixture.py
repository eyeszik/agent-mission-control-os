def _lower_cases(r: random.Random) -> list[str]:
    alphabet = NOISE + ["A", "a", "Ι", ".", "̀", "­", "\U0001d400"]
    out = [SIGMA, "A" + SIGMA, SIGMA + "A", "A" + SIGMA + "A", "Aʰ" + SIGMA, "A" + SIGMA + "ͅ",
           "A" + SIGMA + "ͅA", SIGMA * 3, "A" + SIGMA * 3, "İ", "ẞK"]
    out += ["".join(r.choice(alphabet) for _ in range(r.randrange(1, 9))) for _ in range(800)]
    return out


def build_fixture() -> dict[str, Any]:
    r = random.Random(0xA5109)
    cases = _handwritten() + [(_summary(r), r.sample(TARGETS, r.randrange(4))) for _ in range(1500)]
    assess_rows = []
    for summary, targets in cases:
        result = assess(summary, targets=tuple(targets))  # type: ignore[arg-type]
        assess_rows.append({"summary": summary, "targets": targets,
                            "level": result.level, "codes": list(result.codes)})
    lower_rows = [{"text": t, "lower": t.lower()} for t in _lower_cases(r)]
    return {"protocol": "AMC-FRAMING-PARITY-1", "unidata_version": unicodedata.unidata_version,
            "assess": assess_rows, "lower": lower_rows}


def _regenerate() -> bool:
    return os.environ.get("AMC_REGENERATE_FIXTURES") == "1"


def _load() -> dict[str, Any]:
    if _regenerate() or not FIXTURE.exists():
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(json.dumps(build_fixture(), indent=1, ensure_ascii=True) + "\n")
    return json.loads(FIXTURE.read_text())


def test_casing_module_matches_python_lower() -> None:
    rendered = render_casing_module()
    if _regenerate() or not CASING_MODULE.exists():
        CASING_MODULE.write_text(rendered)
    assert CASING_MODULE.read_text() == rendered


def test_fixture_assess_matches_python() -> None:
    rows = _load()["assess"]
    assert len(rows) >= 1500
    levels = {row["level"] for row in rows}
    assert levels == {"NONE", "REVIEW", "HIGH"}, levels
    for row in rows:
        result = assess(row["summary"], targets=tuple(row["targets"]))
        assert (result.level, list(result.codes)) == (row["level"], row["codes"]), row


def test_fixture_covers_every_code() -> None:
    seen = {code for row in _load()["assess"] for code in row["codes"]}
    assert seen == {"URGENCY", "PRESSURE_TO_APPROVE", "MINIMIZATION", "UNSUPPORTED_ASSURANCE", "OMITS_TARGET"}


def test_fixture_lower_matches_python() -> None:
    rows = _load()["lower"]
    assert len(rows) >= 800
    for row in rows:
        assert row["text"].lower() == row["lower"], row
    assert any(row["lower"].endswith(FINAL_SIGMA) for row in rows)
