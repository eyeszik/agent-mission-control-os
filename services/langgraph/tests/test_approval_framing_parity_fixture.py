"""Approval-framing cross-language parity fixture (Python is the reference).

`packages/pii/tests/fixtures/approval-framing-parity.json` records summaries,
targets and what `security/approval_framing.assess` returns for each, plus
what `str.lower()` returns for a set of strings. `@amc/pii`'s `assessFraming`
and `pyLower` must reproduce every entry. This test checks the stored entries
still match Python, so a change to the module fails here before it silently
breaks the TypeScript twin.

It also owns `packages/pii/src/python-casing.ts`: Python's lowercase mapping
and the two character classes CPython's `str.lower()` consults for the final
sigma rule. They are read from `str.lower()` itself, so the JS engine's
Unicode version never decides what `OMITS_TARGET` sees.

Regenerate both with AMC_REGENERATE_FIXTURES=1, on the Python CI runs (3.11,
Unicode 14.0.0), as for the `@amc/pii` fixture. All values are fictional.
"""
