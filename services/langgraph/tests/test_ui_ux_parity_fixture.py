def test_fixture_covers_every_section() -> None:
    parity, tokens, evaluator = (_load(p) for p in (FIXTURE, TOKENS_FIXTURE, EVALUATOR_FIXTURE))
    minimums = [(parity, "surface", 300), (parity, "features", 400), (parity, "compile", 380),
                (parity, "invalid", 15), (parity, "hashes", 50), (parity, "lax_divergences", 5),
                (parity, "ir_views", FULL_IR_CASES - 2), (tokens, "tokens", 200), (evaluator, "evaluator", 150)]
    for data, section, minimum in minimums:
        assert len(data[section]) >= minimum, section
    assert len(tokens["contrast"]["pairs"]) > 10000
    terminals = {c["ok"]["terminal"] for c in parity["compile"] if "ok" in c}
    assert {"UIUX_SPEC_READY", "REQUIRES_APPROVAL"} <= terminals
    findings = [f for c in evaluator["evaluator"] if "ok" in c for f in c["ok"]["findings"]]
    assert any(f["repaired"] for f in findings) and any(not f["repaired"] for f in findings)


