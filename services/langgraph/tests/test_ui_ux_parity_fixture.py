def _palette(r: random.Random) -> list[str]:
    options = [lambda: _hex(r), lambda: _hex(r).upper(), lambda: _hex(r) + "\n",
               lambda: r.choice(["#12345", "red", "#GGGGGG", "#abcdefg", "", "#fff", " #aabbcc", "#aabbcc "]),
               lambda: r.choice(["#fefefe", "#ffffff", "#f9fafb", "#000000", "#777777", "#767676"])]
    return [r.choice(options)() for _ in range(r.choice([0, 0, 1, 1, 2, 3, 5]))]


