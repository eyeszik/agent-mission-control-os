def _random_request(r: random.Random, index: int) -> dict[str, Any]:
    req: dict[str, Any] = {"project_ref": f"proj-{index}-{r.choice(['a', 'Ü', '日'])}"}
    for key, chance in (("purpose", 0.8), ("primary_user", 0.6), ("primary_task", 0.6), ("business_goal", 0.5),
                        ("surface_hint", 0.4)):
        if r.random() < chance:
            req[key] = _text(r, 1, 7)
    if r.random() < 0.3:
        req["surface"] = r.choice([m.value for m in SurfaceMode])
    if r.random() < 0.2:
        req["platform"] = r.choice(["WEB_RESPONSIVE", "MOBILE_WEB", "DESKTOP_WEB"])
    for key in ("content_requirements", "constraints", "negative_constraints", "existing_components"):
        if r.random() < 0.5:
            req[key] = [_text(r, 1, 4) for _ in range(r.randint(1, 3))]
    for key in ("ai_features", "ai_provider_known", "locale_rtl"):
        if r.random() < 0.3:
            req[key] = r.choice([True, False]) if key != "ai_features" else r.choice([True, False, None])
    if r.random() < 0.8:
        tones = [r.choice(["calm", "precise", "warm", "bold", "Efficient", "reliable", "x-y"]) for _ in range(r.randint(0, 4))]
