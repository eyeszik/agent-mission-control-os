# --- storage ---------------------------------------------------------------------------

def _regenerate() -> bool:
    return os.environ.get("AMC_REGENERATE_FIXTURES") == "1"


def _encode(data: Any) -> str:
    return json.dumps(data, indent=None, separators=(",", ":"), ensure_ascii=True) + "\n"


def _load(path: Path) -> dict[str, Any]:
    if _regenerate() or not path.exists():
        for target, data in build_fixtures().items():
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(_encode(data))
    return json.loads(path.read_text())


