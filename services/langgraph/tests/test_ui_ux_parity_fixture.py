# --- Python's own character table ---------------------------------------------

def _ranges(code_points: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in code_points:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def render_unicode_module() -> str:
    text = "".join(chr(cp) for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF)
    word = _ranges([ord(m.group(0)) for m in re.finditer(r"\w", text)])
    lines = [
        "// GENERATED by services/langgraph/tests/test_ui_ux_parity_fixture.py from Python's re engine.",
        "// Do not edit by hand. Regenerate with AMC_REGENERATE_FIXTURES=1.",
        "",
        "export type CodePointRange = readonly [number, number];",
        "",
        f"export const PYTHON_UNIDATA_VERSION = '{unicodedata.unidata_version}';",
        "",
        "/** Code points Python's `\\w` matches in a str pattern. */",
        "export const WORD_RANGES: readonly CodePointRange[] = [",
    ]
    lines += [f"  [0x{a:x}, 0x{b:x}]," for a, b in word]
    lines += ["];", ""]
    return "\n".join(lines)


# --- helpers ---------------------------------------------------------------------

def outcome(run: Callable[[], Any]) -> dict[str, Any]:
    try:
        return {"ok": run()}
    except ValidationError:
        return {"raises": {"error": "ValidationError"}}
    except (ValueError, KeyError, IndexError) as exc:
        return {"raises": {"error": type(exc).__name__, "message": str(exc)}}


def dump(model: Any) -> Any:
    return model.model_dump(mode="json")


def tag(value: Any) -> Any:
    if isinstance(value, float):
        return {"$float": repr(value)}
    if isinstance(value, (list, tuple)):
        return [tag(v) for v in value]
    if isinstance(value, dict):
        return {k: tag(v) for k, v in value.items()}
    return value


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


