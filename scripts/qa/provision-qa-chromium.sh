#!/usr/bin/env bash
# Provision a local Chromium for the UCPO browser QA gate (services/langgraph/agency/ucpo/qa.py).
#
# Why: Playwright's own browser download host is not reachable from this sandbox. The QA runner
# launches Chromium from Playwright's cache, so this script places a Chromium build there, at the exact
# paths Playwright 1.64 expects. Source: npm package @sparticuz/chromium (MIT), pinned to 153.0.0.
#
# Honest limits: this is a stand-in binary, not an official Playwright download. It is used only to
# run the local QA gate. CI should install Playwright's own Chromium (`pnpm exec playwright install chromium`).
# Re-run after any environment reset: the cache and the scratch copy live outside the repository.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
SCRATCH="${AMC_QA_SCRATCH:-/tmp/amc-qa-chromium}"
PKG_VERSION="153.0.0"
CACHE="${PLAYWRIGHT_BROWSERS_PATH:-$HOME/.cache/ms-playwright}"

command -v node >/dev/null || { echo "node is required" >&2; exit 1; }
mkdir -p "$SCRATCH"
cd "$SCRATCH"
[ -f package.json ] || npm init -y >/dev/null
npm install --no-save --ignore-scripts "@sparticuz/chromium@${PKG_VERSION}" >/dev/null 2>&1
BIN_DIR="$SCRATCH/node_modules/@sparticuz/chromium/bin"

# 1. The Chromium binary, decompressed from the package's brotli archive.
node -e '
const fs = require("fs"), zlib = require("zlib");
const src = process.argv[1], dst = process.argv[2];
fs.writeFileSync(dst, zlib.brotliDecompressSync(fs.readFileSync(src)));
' "$BIN_DIR/chromium.br" "$SCRATCH/chromium-real"
chmod 755 "$SCRATCH/chromium-real"

# 2. Shared libraries the binary needs (the sandbox env is scrubbed, so they are reached via the wrapper).
rm -rf "$SCRATCH/al2023" && mkdir -p "$SCRATCH/al2023"
node -e '
const fs = require("fs"), zlib = require("zlib");
fs.writeFileSync(process.argv[2], zlib.brotliDecompressSync(fs.readFileSync(process.argv[1])));
' "$BIN_DIR/al2023.tar.br" "$SCRATCH/al2023.tar"
tar -xf "$SCRATCH/al2023.tar" -C "$SCRATCH/al2023"
LIBDIR="$(dirname "$(find "$SCRATCH/al2023" -name 'libnspr4.so' | head -1)")"
[ -d "$LIBDIR" ] || { echo "al2023 libraries not found" >&2; exit 1; }

# 3. The exact Playwright-expected executable paths, from the repo's pinned playwright-core.
PW_CORE="$(ls -d "$REPO"/node_modules/.pnpm/playwright-core@1.65.0/node_modules/playwright-core | head -1)"
EXE="$(node -e 'console.log(require(process.argv[1]).chromium.executablePath())' "$PW_CORE")"
# Playwright 1.65 runs default headless with a separate headless-shell build, at a path derived from the same revision.
REV="$(basename "$(dirname "$(dirname "$EXE")")" | sed 's/^chromium-//')"
SHELL_EXE="$CACHE/chromium_headless_shell-${REV}/chrome-headless-shell-linux64/chrome-headless-shell"

install_wrapper() {  # $1 = target path, $2 = wrapper name for the real binary
  local target="$1" dir
  dir="$(dirname "$target")"
  mkdir -p "$dir"
  cp "$SCRATCH/chromium-real" "$dir/chromium-real"
  cat > "$target" <<WRAP
#!/bin/sh
# Local QA wrapper for @sparticuz/chromium ${PKG_VERSION}. Generated by scripts/qa/provision-qa-chromium.sh.
LD_LIBRARY_PATH=${LIBDIR}
export LD_LIBRARY_PATH
exec "\$(dirname "\$0")/chromium-real" --no-zygote "\$@"
WRAP
  chmod 755 "$target"
}
install_wrapper "$EXE"
install_wrapper "$SHELL_EXE"

# 4. Smoke test: Playwright must launch it with the same default arguments the QA runner uses.
cat > "$REPO/apps/web/.qa-provision-probe.cjs" <<'PROBE'
const pw = require("@playwright/test");
(async () => {
  const b = await pw.chromium.launch({ args: ["--no-sandbox"], timeout: 60000 });
  const p = await b.newPage();
  await p.setContent("<h1>probe</h1>");
  console.log("OK", b.version(), await p.textContent("h1"));
  await b.close();
})().catch((e) => { console.error("FAIL", e.message.slice(0, 400)); process.exit(1); });
PROBE
(cd "$REPO/apps/web" && env -i PATH=/usr/local/bin:/usr/bin:/bin HOME="$HOME" LD_LIBRARY_PATH= node .qa-provision-probe.cjs) || true
rm -f "$REPO/apps/web/.qa-provision-probe.cjs"
echo "provisioned: $EXE"
